def test_record_round_trip_and_bitwise_rerun(fits):
    noisy = fits['noisy']
    estimator, experiments = noisy['estimator'], noisy['experiments']
    names = list(estimator.name_params_total)
    assert len(names) == cryst.NUM_KINETIC_PARAMS
    record = CalibrationRecord.from_estimation(
        estimator, experiments, case='batch-crystallizer-growth-stand-in',
        parameter_units=dict(zip(names, PARAMETER_UNITS)),
        model=ModelRevision(
            'BatchCryst.paramest_wrapper',
            description=('Seeded growth-only BatchCryst, method of '
                         'moments, of test_crystallizer_paramest_'
                         'requested_rows; k_g and g estimated')),
        sources=[DataSource(
            'model-generated', 'synthetic',
            'generated by this test module; no external data',
            description=('BatchCryst outputs at k_g = 1 um/s, g = 1 plus '
                         'Gaussian noise of the declared standard '
                         'deviations (numpy default_rng seed 352)'))],
        model_solver=MODEL_SOLVER)
    loaded = CalibrationRecord.from_json(record.to_json())

    assert loaded == record
    assert [item.name for item in loaded.parameters] == names
    assert [item.optimized for item in loaded.parameters] == [
        index in cryst.ACTIVE_COLUMNS
        for index in range(cryst.NUM_KINETIC_PARAMS)]
    validation.case.assert_bits_equal(loaded.fitted_values, noisy['params'])
    validation.case.assert_bits_equal(loaded.covariance,
                                      noisy['covariance'])
    measurement = loaded.experiments['run'].measurements['c_A']
    validation.case.assert_bits_equal(
        measurement.values,
        experiments['run'].measurements['c_A'].values)

    rerun = loaded.rerun(cryst._crystallizer().paramest_wrapper,
                         rtol=REPLAY_RTOL, atol=REPLAY_ATOL)
    # Repeatability: the same data, seed and options through the same
    # deterministic solves and iterations reproduce the fit bit for bit.
    validation.case.assert_bits_equal(rerun.params_convg, noisy['params'])
