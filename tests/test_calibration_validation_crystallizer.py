"""Calibration validation of the crystallizer stand-in (#352, AC2-AC6).

Scope: the shared public estimation contract on the crystallizer
estimation path, ``BatchCryst.paramest_wrapper`` -> ``ParameterEstimation``,
the crystallization stand-in of #352 while the December crystallization
demonstrator (#358) is not on master: recovery of known parameters and a
fixed-seed interval check; the derivative check of the CVODES moment
sensitivities against central differences of complete solves (AC2);
observations left unchanged by the analyses and bitwise repeatability
(AC3); the identifiability report, with its noise assumption and the strong
correlation of the growth rate constant and growth order, its verdict
derived from the floor and the singular values for a sensitivity accuracy
established by the derivative checks (AC4); the convergence
outcome and tolerances (AC5); and ``CalibrationRecord`` capture, JSON round
trip and rerun (AC6).

Stand-in status: the data are synthetic, generated by the model itself at
known parameters; the fits verify the estimation contract and are not
evidence of an empirical calibration. Fixture: the seeded growth-only
``BatchCryst`` (moments) of ``test_crystallizer_paramest_requested_rows``
(charged at 310 K with 93.3 kg/m**3 of A against a constant solubility of
2 kg/m**3), whose true growth rate constant is k_g = 1 um/s and growth
order g = 1. Only k_g and g are estimated, selected through ``mask_params``
and ``optimize_flags`` (an unmasked sensitivity solve stalls, issue #222).
The model is sampled every 3 s from 3 s to 30 s, after the charge at 0 s
(the row selection of issue #328), without replicate times (the heat duty
is NaN at repeated times, issue #314); it measures the A concentration
[kg/m**3] and the third moment [um**3]. Two datasets: noise-free, and with
Gaussian noise from ``numpy.random.default_rng`` with a fixed seed whose
standard deviations the measurements declare (``Measurement.uncertainty``),
so the declared-uncertainty noise assumption holds exactly by construction.
The fits are Levenberg-Marquardt from the seed (0.7 um/s, 1.2), because
SciPy fits cannot be recorded yet (#534). The record names all 13 kinetic
parameters, because ``SimulationExec`` names a masked parameter vector
inconsistently (#535). Assimulo lane; about 15 s (two fits of 3-5 s, a
rerun of about 5 s and two derivative checks of about 1 s).
"""

import warnings

import numpy as np
import pytest
from scipy import stats

pytestmark = [pytest.mark.assimulo, pytest.mark.integration]
pytest.importorskip('assimulo')

import test_calibration_validation_decay as validation
import test_crystallizer_paramest_requested_rows as cryst
from PharmaPy.ParamEstim import Experiment, Measurement, ParameterEstimation
from PharmaPy.Records import CalibrationRecord, DataSource, ModelRevision

EPS = np.finfo(float).eps  # [-], float64 machine epsilon
# True growth rate constant [um/s] and order [-] of the fixture.
TRUE_PARAMS = np.array([cryst.GROWTH[0], cryst.GROWTH[2]])  # [um/s], [-]
# Seed of the fits: 30 % below the true k_g and 20 % above the true g, far
# enough that LM takes over ten evaluations, inside its basin of
# convergence (prototype fits converged in 15 and 23 evaluations).
SEED = np.array([0.7, 1.2])  # [um/s], [-]
# Sample times after the charge (#328), no replicates (#314), spanning the
# fixture's 30 s horizon, over which c_A falls from 93 to about 5 kg/m**3.
SAMPLE_TIMES = np.arange(3.0, 31.0, 3.0)  # [s]
MOMENT_3_COLUMN = cryst.NUM_MOMENTS - 1  # third moment mu_3 [um**3]
# Measurement name -> (paramest_wrapper output column, units).
MEASURED = {'c_A': (cryst.TARGET_COLUMN, 'kg/m**3'),
            'mu_3': (MOMENT_3_COLUMN, 'um**3')}
# Noise standard deviations, design assumption: about 0.5 % of the charged
# c_A (93 kg/m**3) and 1 % of the final mu_3 (2.9e17 um**3), visible noise
# far above the 1e-6 relative solver accuracy that still determines both
# parameters to a few percent.
NOISE_STD = {'c_A': 0.5, 'mu_3': 3e15}  # [kg/m**3], [um**3]
NOISE_SEED = 352  # [-], arbitrary fixed numpy.random.default_rng seed
ALPHA = 0.95  # [-], confidence level of the interval check
# Units of the 13 CrystKinetics parameters in concat_params order, from the
# CrystKinetics docstring with the default relative supersaturation [-]:
# prefactors carry the rate units (nucleation [#/m**3/s], growth and
# dissolution [um/s]); the secondary prefactor is further divided by the
# moment basis to the power s_2; activation energies [J/mol]; orders [-].
PARAMETER_UNITS = ['#/m**3/s', 'J/mol', '-',
                   '#/m**3/s/(moment basis)**s_2', 'J/mol', '-', '-',
                   'um/s', 'J/mol', '-', 'um/s', 'J/mol', '-']
# CVode settings of the fits: Assimulo's defaults (cryst.CVODE_RTOL and
# CVODE_ATOL, recorded in BatchCryst.sundials_opt).
MODEL_SOLVER = {'integrator': 'Assimulo CVode', 'rtol': cryst.CVODE_RTOL,
                'atol': cryst.CVODE_ATOL}  # rtol [-]; atol [state units]
# Tightened CVode tolerances of the sharp derivative check. atol equals
# rtol numerically: every state exceeds 1 in its unit (c_A >= 4.5 kg/m**3,
# volume about 2 m**3, moments >= 7e8 um**n), so rtol governs. Tighter
# settings (rtol = atol = 1e-10) made a check take minutes in prototypes.
TIGHT_RTOL = 1e-8  # [-]
TIGHT_ATOL = 1e-8  # [state units]
# Relative central-difference steps h = r**(1/3) for outputs accurate to the
# CVode rtol r (check_derivatives Notes).
DEFAULT_REL_STEP = cryst.CVODE_RTOL ** (1 / 3)  # [-], 1e-2
TIGHT_REL_STEP = TIGHT_RTOL ** (1 / 3)  # [-], 2.15e-3
REPLAY_RTOL = validation.case.REPLAY_RTOL  # [-], four ulps
REPLAY_ATOL = 0.0  # [um/s or -]
# Practical-identifiability threshold of the correlation test, a design
# threshold: a standard error inflated at least tenfold over its value with
# the other parameter known (1 / sqrt(1 - c**2) >= 10, i.e. |c| >= 0.995)
# means the data determine essentially one combination of k_g and g, each
# parameter only through the other. The fixture's inflation is about 15.
LIMITING_INFLATION = 10.0  # [-]
# Two scaled sensitivity rows give the Gram matrix [[1, c], [c, 1]], whose
# eigenvalues 1 +/- |c| and eigenvectors (1, +/-1) / sqrt(2) the SVD
# returns to about eps / (1 - |c|) ~ 1e-13 here (|c| ~ 0.998); 1e-9 bounds
# it.
STRUCTURE_RTOL = 1e-9  # [-]


def truncation_scale():
    """Return the truncation constant of the derivative-check error model.

    Returns
    -------
    float
        ``max(1, ln(sigma_0)**2)`` [-], with ``sigma_0 = c_A0 / c_sat - 1``
        the relative supersaturation at the charge (CrystKinetics default
        driving force). The growth rate is ``k_g * sigma**g``, so each
        derivative in g multiplies by ``ln(sigma)``: the ratio of third to
        first derivatives, the truncation constant of the central
        difference, scales with ``ln(sigma)**2`` (about 14.6 here). The k_g
        rows are taken with a unit constant.
    """
    charged = cryst._charged_state()[cryst.TARGET_COLUMN]  # [kg/m**3]
    supersaturation = charged / cryst.SATURATION - 1  # [-]
    return max(1.0, np.log(supersaturation) ** 2)


def derivative_bound(rel_step, solver_rtol):
    """Return the agreement bound of a crystallizer derivative check.

    Parameters
    ----------
    rel_step : float
        Relative central-difference step h [-] (the parameters are O(1)).
    solver_rtol : float
        CVode relative tolerance r of the outputs [-].

    Returns
    -------
    float
        ``SOLVER_CHECK_SAFETY * (C_T h**2 + r / h)`` [-]
        (``truncation_scale`` for C_T).
    """
    return validation.SOLVER_CHECK_SAFETY * (
        truncation_scale() * rel_step ** 2 + solver_rtol / rel_step)


def full_vector(growth):
    """Return the 13 kinetic parameters with the growth entries set.

    Parameters
    ----------
    growth : sequence of float
        k_g [um/s] and g [-].

    Returns
    -------
    numpy.ndarray
        ``CrystKinetics.concat_params`` order, the other entries those of
        the fixture (zeros).
    """
    # CrystKinetics parameter units (PARAMETER_UNITS)
    params = cryst._crystallizer().Kinetics.concat_params().astype(float)
    params[cryst.ACTIVE_COLUMNS] = growth
    return params


def make_experiments(observations, run_args=None):
    """Build the one-run experiment set of the synthetic data.

    Parameters
    ----------
    observations : dict
        Measurement name -> values on ``SAMPLE_TIMES`` [kg/m**3 or um**3].
    run_args : dict, optional
        ``solve_unit`` keywords bound to the experiment.

    Returns
    -------
    dict
        ``{'run': Experiment}``, measurements declaring ``NOISE_STD``.
    """
    measurements = {
        name: Measurement(column, SAMPLE_TIMES, observations[name],
                          uncertainty=NOISE_STD[name], units=units,
                          x_units='s')
        for name, (column, units) in MEASURED.items()}
    kwargs = {} if run_args is None else {'run_args': run_args}
    return {'run': Experiment(measurements, kwargs=kwargs)}


def make_estimator(experiments):
    """Build the masked growth estimator from the perturbed seed.

    Parameters
    ----------
    experiments : dict
        Experiment set of ``make_experiments``.

    Returns
    -------
    ParameterEstimation
        Unfitted estimator of k_g and g over a fresh crystallizer, with the
        13 kinetic parameter names.
    """
    unit = cryst._crystallizer()
    flags = np.zeros(cryst.NUM_KINETIC_PARAMS, dtype=bool)
    flags[cryst.ACTIVE_COLUMNS] = True
    return ParameterEstimation(unit.paramest_wrapper, full_vector(SEED),
                               experiments, optimize_flags=list(flags),
                               name_params=list(unit.Kinetics.name_params))


def fitted(experiments):
    """Fit the growth parameters and collect non-convergence warnings.

    Parameters
    ----------
    experiments : dict
        Experiment set.

    Returns
    -------
    dict
        ``estimator``, ``experiments``, the returned ``params`` [um/s, -],
        ``covariance`` and ``info``, and ``unconverged`` (warning messages
        stating that the fit stopped without converging).
    """
    estimator = make_estimator(experiments)
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter('always')
        params, covariance, info = estimator.optimize_fn(verbose=False)
    return {'estimator': estimator, 'experiments': experiments,
            'params': params, 'covariance': covariance, 'info': info,
            'unconverged': [str(item.message) for item in caught
                            if 'stopped without converging'
                            in str(item.message)]}


@pytest.fixture(scope='module')
def fits():
    """Generate the datasets and fit both once.

    Returns
    -------
    dict
        ``clean`` and ``noisy`` (``fitted`` results) and ``truth``, the
        noise-free model outputs [kg/m**3, um**3] per measurement.
    """
    # paramest_wrapper state units: mu_n [um**n], mass_conc [kg/m**3], ...
    states, _ = cryst._crystallizer().paramest_wrapper(
        full_vector(TRUE_PARAMS), SAMPLE_TIMES)
    truth = {name: states[:, column] for name, (column, _)
             in MEASURED.items()}  # [kg/m**3], [um**3]
    generator = np.random.default_rng(NOISE_SEED)
    noisy = {name: truth[name] + NOISE_STD[name]
             * generator.standard_normal(SAMPLE_TIMES.size)
             for name in MEASURED}  # [kg/m**3], [um**3]
    return {'truth': truth, 'clean': fitted(make_experiments(truth)),
            'noisy': fitted(make_experiments(noisy))}


def test_noise_free_fit_recovers_the_true_parameters(fits):
    """Recovery to the solver accuracy propagated through the fit.

    Data and model are CVode solutions at the default tolerances, each
    output accurate to one tolerance unit ``rtol |y| + atol`` (the
    allowance of ``test_self_generated_data_give_zero_objective``), so the
    weighted residual vector at the true parameters may be wrong by
    ``||delta r|| <= 2 ||(rtol |y| + atol) / sigma||``. The linearized
    least-squares estimate moves by ``inv(J J^T) J delta r``, whose entry i
    is at most ``sqrt(inv(J J^T)_ii) ||delta r||``, the absolute-form
    standard error times ``||delta r||``; LM's relative step test adds
    ``eps_2 |p|``.
    """
    clean = fits['clean']
    params = clean['params']  # [um/s], [-]
    # The standard errors do not depend on jacobian_rtol.
    report = clean['estimator'].get_identifiability(include_mse=False)
    tolerance_units = np.concatenate([
        (cryst.CVODE_RTOL * np.abs(fits['truth'][name]) + cryst.CVODE_ATOL)
        / NOISE_STD[name] for name in MEASURED])  # [-]
    residual_error = 2 * np.linalg.norm(tolerance_units)  # [-]
    bound = (report.standard_errors * residual_error
             + validation.LM_TOLERANCES['eps_2']
             * np.abs(params))  # [um/s], [-]
    np.testing.assert_array_less(np.abs(params - TRUE_PARAMS), bound)


@pytest.mark.parametrize('include_mse', [False, True])
def test_noisy_fit_intervals_contain_the_true_parameters(fits, include_mse):
    """Fixed-seed check, not a coverage claim.

    With the declared standard deviations equal to the generated noise,
    ``include_mse=False`` is the exact noise model and ``True`` re-estimates
    its scale. For this one seed the 95 % intervals of both forms contain
    the true parameters; over many seeds they would miss in about 5 % of
    the datasets, which this test does not assess.
    """
    estimator = fits['noisy']['estimator']
    report = estimator.get_identifiability(alpha=ALPHA,
                                           include_mse=include_mse)

    assert report.noise_model == 'declared_uncertainty'
    assert 'Measurement.uncertainty' in report.noise_assumption
    assert report.variance_scale_estimated is include_mse
    lower, upper = report.confidence_intervals.T  # [um/s], [-]
    assert np.all(lower < TRUE_PARAMS) and np.all(TRUE_PARAMS < upper)
    # The intervals are estimate -/+ t * SE with the Student-t quantile of
    # num_observed - 2 degrees of freedom.
    num_observed = len(MEASURED) * SAMPLE_TIMES.size  # [-]
    quantile = stats.t.ppf((1 + ALPHA) / 2, num_observed - 2)  # [-]
    np.testing.assert_allclose(
        upper - lower, 2 * quantile * report.standard_errors,
        rtol=STRUCTURE_RTOL)


@pytest.fixture(scope='module')
def checks(fits):
    """Check the CVODES sensitivities at the noisy fit, twice.

    The fitted estimator is checked as it is (CVode rtol 1e-6, step
    ``rtol**(1/3)``). A second estimator binds tightened CVode tolerances
    through ``run_args`` and is checked at the same parameters, which
    verifies the same sensitivity equations with a reference accurate to
    about 1e-4 instead of 1e-2. Both bounds follow ``derivative_bound``.

    Returns
    -------
    dict
        ``'default'`` and ``'tight'``: ``(DerivativeCheck, bound [-])``.
    """
    noisy = fits['noisy']
    params = noisy['params']  # [um/s], [-]
    tight_experiments = make_experiments(
        {name: noisy['experiments']['run'].measurements[name].values
         for name in MEASURED},
        run_args={'sundials_opts': {'rtol': TIGHT_RTOL,
                                    'atol': TIGHT_ATOL}})
    results = {}
    for label, estimator, rel_step, solver_rtol in (
            ('default', noisy['estimator'], DEFAULT_REL_STEP,
             cryst.CVODE_RTOL),
            ('tight', make_estimator(tight_experiments), TIGHT_REL_STEP,
             TIGHT_RTOL)):
        bound = derivative_bound(rel_step, solver_rtol)  # [-]
        # (DerivativeCheck, its agreement bound [-])
        results[label] = (estimator.check_derivatives(
            params=params, rel_step=rel_step, rtol=bound), bound)
    return results


def sensitivity_accuracy(checks):
    """Bound the row errors of the default-tolerance CVODES sensitivities.

    Parameters
    ----------
    checks : dict
        The ``checks`` fixture.

    Returns
    -------
    numpy.ndarray
        Row-relative accuracy [-] of the fit's sensitivity rows, shape (2,):
        their measured distance from the tightened-tolerance rows plus
        twice the tight bound. A tight row that agrees with its reference
        to the bound, whose own error is at most the bound by the error
        model, is within twice the bound of the exact row (triangle
        inequality, to first order in these small bounds).
    """
    default_check, _ = checks['default']
    tight_check, tight_bound = checks['tight']
    tight_rows = tight_check.jacobian  # [weighted residual / p_i]
    distance = np.linalg.norm(default_check.jacobian - tight_rows,
                              axis=1)  # [weighted residual / p_i]
    return (distance / np.linalg.norm(tight_rows, axis=1)
            + 2 * tight_bound)  # [-]


def test_cvodes_sensitivities_agree_with_central_differences(checks):
    for check, bound in checks.values():
        assert check.jacobian_source == 'model'
        assert check.parameter_names == ('k_{g}', 'g')
        assert check.formulas == ('central', 'central')
        assert check.observed.all()
        assert check.agrees.all(), check.summary()
        # A sensitivity row wrong by 10 % is flagged: its error of 0.1 is
        # about 6 (default) or 140 (tight) times the bound.
        assert (validation.MIN_POWER_MARGIN * bound
                <= validation.deriv.WRONG_FACTOR - 1)


def test_identifiability_shows_the_growth_correlation(fits, checks):
    """k_g and g compensate each other: a practical-identifiability limit.

    Raising the order g raises sigma**g (sigma > 1 throughout), which a
    smaller k_g offsets, so the scaled sensitivity rows are nearly
    parallel (cosine c near 1) and the parameters strongly negatively
    correlated. For two parameters the report's quantities follow from c
    alone: singular values ``sqrt(1 +/- c)``, correlation ``-c``, weakest
    direction ``(1, -1) / sqrt(2)`` and a variance-inflation factor
    ``1 / sqrt(1 - c**2)`` of each standard error over its value with the
    other parameter fixed. Prototype values: c = 0.998, inflation 15,
    collinearity index 21, scaled condition number 900. The sensitivity
    accuracy passed as ``jacobian_rtol`` is established by the derivative
    checks (``sensitivity_accuracy``), not assumed to be the CVode rtol.
    """
    estimator = fits['noisy']['estimator']
    accuracy = sensitivity_accuracy(checks)  # [-]
    report = estimator.get_identifiability(jacobian_rtol=accuracy)

    assert report.parameter_names == ('k_{g}', 'g')
    assert report.noise_model == 'declared_uncertainty'
    assert 'Measurement.uncertainty' in report.noise_assumption
    np.testing.assert_array_equal(report.jacobian_rtol, accuracy)
    information = report.information_matrix  # [1/(p_i p_j)]
    cosine = information[0, 1] / np.sqrt(
        information[0, 0] * information[1, 1])  # [-]
    assert 0 < cosine < 1
    np.testing.assert_allclose(report.singular_values,
                               np.sqrt([1 + cosine, 1 - cosine]),
                               rtol=STRUCTURE_RTOL)
    assert report.correlation[0, 1] == pytest.approx(-cosine,
                                                     rel=STRUCTURE_RTOL)
    weakest = report.weakest_direction
    components = np.asarray(weakest.components)  # [-]
    components = components * np.sign(components[0])
    np.testing.assert_allclose(components, [np.sqrt(0.5), -np.sqrt(0.5)],
                               rtol=STRUCTURE_RTOL)
    # Marginal over conditional standard error: sqrt(s2 / A_ii) is the
    # standard error with the other parameter fixed.
    conditional = np.sqrt(report.residual_mean_square
                          / np.diag(information))  # [um/s], [-]
    inflation = 1 / np.sqrt(1 - cosine ** 2)  # [-]
    np.testing.assert_allclose(report.standard_errors / conditional,
                               inflation, rtol=STRUCTURE_RTOL)
    # The limitation, in magnitude: neither parameter is determined to
    # better than a tenth of the precision it would have if the other were
    # known (design threshold, see LIMITING_INFLATION).
    assert inflation >= LIMITING_INFLATION

    # Verdict by the report's own criterion: the floor is the norm of the
    # row bounds; the smaller singular value exceeds it and passes the #532
    # test, so the parameters are identifiable despite the correlation.
    floor = np.linalg.norm(accuracy)  # [-]
    assert report.resolution_floor == pytest.approx(floor,
                                                    rel=STRUCTURE_RTOL)
    smallest = np.sqrt(1 - cosine)  # [-]
    assert smallest > floor and smallest ** 2 > EPS * (1 + cosine)
    assert report.identifiable is True
    assert report.unresolved_directions == ()
    assert report.collinearity_index == pytest.approx(1 / smallest,
                                                      rel=STRUCTURE_RTOL)


def test_observations_are_unchanged_by_the_analyses(fits):
    noisy = fits['noisy']
    estimator, experiments = noisy['estimator'], noisy['experiments']
    before = validation.snapshot(estimator, experiments)

    estimator.get_confidence_intervals(verbose=False)
    estimator.get_identifiability()
    estimator.check_derivatives(rel_step=DEFAULT_REL_STEP)

    validation.assert_same_snapshot(
        validation.snapshot(estimator, experiments), before)
    validation.case.assert_bits_equal(estimator.params_convg,
                                      noisy['params'])


