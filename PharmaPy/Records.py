def _derivative_descriptor(derivatives) -> dict:
    """Validate and encode how parameter sensitivities were obtained.

    Parameters
    ----------
    derivatives : Mapping
        ``'jacobian'``: one of ``JACOBIAN_SOURCES``; ``'dx_finitediff'``:
        ``'default'``, ``'callable'``, or the numeric finite-difference step
        (a real scalar or array, in parameter units).

    Returns
    -------
    dict
        Encoded descriptor.

    Raises
    ------
    TypeError
        If ``derivatives`` is not a mapping or the step is neither a
        descriptor nor numeric.
    ValueError
        If keys are missing or unknown, the source or descriptor is
        unknown, or the step is not finite.
    """
    if not isinstance(derivatives, Mapping):
        raise TypeError("SolverSettings derivatives must be a mapping; got "
                        f"{type(derivatives).__name__}")
    _check_keys(dict(derivatives), ('jacobian', 'dx_finitediff'), (),
                'SolverSettings derivatives')
    jacobian = _choice(derivatives['jacobian'], JACOBIAN_SOURCES,
                       'SolverSettings derivatives jacobian')
    step = derivatives['dx_finitediff']
    label = 'SolverSettings derivatives dx_finitediff'
    if isinstance(step, str):
        _choice(step, STEP_DESCRIPTORS, label)
    elif isinstance(step, (bool, np.bool_)) or not isinstance(
            step, (numbers.Real, np.ndarray)):
        raise TypeError(f"{label} must be {STEP_DESCRIPTORS!r} or a real "
                        f"number or array; got {type(step).__name__}")
    elif isinstance(step, np.ndarray) and step.dtype.kind not in 'iuf':
        raise TypeError(f"{label} must be a real array; got dtype "
                        f"{step.dtype}")
    return {'jacobian': jacobian,
            'dx_finitediff': _encode_value(step, label)}


class SolverSettings(_ImmutableRecord):
    """Optimizer settings and outcome of a parameter estimation.

    Parameters
    ----------
    method : {'LM', 'IPOPT'}
        ``method`` of ``ParameterEstimation.optimize_fn``.
    options : Mapping[str, object], optional
        Effective optimizer options of the fit: the ``optim_options`` given
        to ``optimize_fn`` without the entries it sets itself, plus, for
        IPOPT, the entries cyipopt writes into ``optimize_fn``'s private
        copy (its defaults). ``optimize_fn`` sets ``'full_output'`` and
        ``'verbose'`` (LM) or ``'print_level'`` (IPOPT) in that copy; such
        entries given here are recorded as given and replaced again on a
        rerun, without effect on the fit.
    default_options : Mapping[str, object], optional
        Optimizer defaults in force for the options that ``options`` does
        not set, e.g. the ``levenberg_marquardt`` keyword defaults
        ``max_fun_eval``, ``eps_1``, ``eps_2`` and ``tol_fun`` of an LM fit
        (issue #483). No key may also appear in ``options``. None (the
        default) states that they were not recorded: records written before
        this entry existed, and IPOPT fits. The ``options`` of an IPOPT fit
        hold the caller's options plus the entries cyipopt writes into
        ``optimize_fn``'s private copy (``tol``, ``mu_strategy``,
        ``hessian_approximation``; ``print_level`` is injected by
        ``optimize_fn`` and omitted); Ipopt's native defaults, e.g.
        ``max_iter`` and ``acceptable_tol``, are not recorded.
    model_solver : Mapping[str, object], optional
        Settings of the model's own solver, e.g. CVode ``rtol``/``atol``
        passed through the model callback, for documentation.
    outcome : Mapping[str, object], optional
        Optimizer outcome, e.g. ``'stop_criterion'``, ``'num_iter'``,
        ``'num_fun_eval'`` (available from LM only) and ``'objective'``.
    derivatives : Mapping, optional
        How the parameter sensitivities were obtained: ``'jacobian'`` is
        one of ``JACOBIAN_SOURCES`` and ``'dx_finitediff'`` is
        ``'default'`` (the step of magnitude ``1e-3 * max(|p|, 1e-6)``
        that ``ParameterEstimation`` installs), ``'callable'`` (a user
        function, not recordable) or the numeric step in parameter units,
        replayed by ``CalibrationRecord.estimation_inputs``. None if
        unknown.

    Raises
    ------
    TypeError
        If a mapping is not a mapping with str keys or holds an
        unsupported value.
    ValueError
        If ``method``, the Jacobian source or the step descriptor is
        unknown, a value is not finite, or a key appears in both
        ``options`` and ``default_options``.

    Notes
    -----
    Mapping values follow the record codec (see the module docstring).
    ``options`` keeps the settings as written by the caller;
    ``CalibrationRecord.optimizer_inputs`` merges ``default_options`` under
    them so that a rerun uses the settings of the original fit.
    """

    __slots__ = ('_method', '_options', '_default_options', '_model_solver',
                 '_outcome', '_derivatives')

    def __init__(self, method: str, *, options: Optional[Mapping] = None,
                 default_options: Optional[Mapping] = None,
                 model_solver: Optional[Mapping] = None,
                 outcome: Optional[Mapping] = None,
                 derivatives: Optional[Mapping] = None) -> None:
        """Validate and store the settings.

        Parameters
        ----------
        method, options, default_options, model_solver, outcome, derivatives
            See the class docstring.

        Raises
        ------
        TypeError, ValueError
            See the class docstring.
        """
        self._set('_method', _choice(method, OPTIMIZATION_METHODS,
                                     'SolverSettings method'))
        self._set('_options', _encode_mapping(
            {} if options is None else options, 'SolverSettings options'))
        if default_options is not None:
            default_options = _encode_mapping(
                default_options, 'SolverSettings default_options')
            repeated = [key for key in default_options
                        if key in self._options]
            if repeated:
                raise ValueError(
                    f"SolverSettings default_options {repeated!r} are also "
                    "given in options; an option is either set by the "
                    "caller or defaulted, not both")
        self._set('_default_options', default_options)
        self._set('_model_solver', None if model_solver is None else
                  _encode_mapping(model_solver,
                                  'SolverSettings model_solver'))
        self._set('_outcome', None if outcome is None else
                  _encode_mapping(outcome, 'SolverSettings outcome'))
        self._set('_derivatives', None if derivatives is None else
                  _derivative_descriptor(derivatives))

    @property
    def method(self) -> str:
        """Optimization method.

        Returns
        -------
        str
            One of ``OPTIMIZATION_METHODS``.
        """
        return self._method

    @property
    def options(self) -> dict:
        """Optimizer options.

        Returns
        -------
        dict
            New dict on every access, so ``optimize_fn`` cannot change the
            record.
        """
        return _decode_mapping(self._options, 'SolverSettings options')

    @property
    def default_options(self) -> Optional[dict]:
        """Optimizer defaults in force for the options not given.

        Returns
        -------
        dict or None
            New dict on every access, without any key of ``options``, or
            None if the defaults were not recorded (see the class
            docstring).
        """
        return (None if self._default_options is None else
                _decode_mapping(self._default_options,
                                'SolverSettings default_options'))

    @property
    def model_solver(self) -> Optional[dict]:
        """Settings of the model's own solver.

        Returns
        -------
        dict or None
            New dict on every access, or None.
        """
        return (None if self._model_solver is None else
                _decode_mapping(self._model_solver,
                                'SolverSettings model_solver'))

    @property
    def outcome(self) -> Optional[dict]:
        """Optimizer outcome.

        Returns
        -------
        dict or None
            New dict on every access, or None.
        """
        return (None if self._outcome is None else
                _decode_mapping(self._outcome, 'SolverSettings outcome'))

    @property
    def derivatives(self) -> Optional[dict]:
        """How the parameter sensitivities were obtained.

        Returns
        -------
        dict or None
            New dict with ``'jacobian'`` and ``'dx_finitediff'`` (a
            descriptor str or the numeric step in parameter units), or None
            if unknown.
        """
        return (None if self._derivatives is None else
                _decode_mapping(self._derivatives,
                                'SolverSettings derivatives'))

    def to_dict(self) -> dict:
        """Serialize the settings.

        Returns
        -------
        dict
            JSON object with keys ``method``, ``options``,
            ``default_options``, ``model_solver``, ``outcome`` and
            ``derivatives``.
        """
        return json.loads(json.dumps(
            {'method': self._method, 'options': self._options,
             'default_options': self._default_options,
             'model_solver': self._model_solver,
             'outcome': self._outcome, 'derivatives': self._derivatives}))

    @classmethod
    def from_dict(cls, data: dict) -> 'SolverSettings':
        """Reconstruct settings written by ``to_dict``.

        Parameters
        ----------
        data : dict
            JSON object; all keys but ``method`` may be omitted. An omitted
            ``default_options``, as in records written before it existed
            (issue #483), reads as None.

        Returns
        -------
        SolverSettings
            New settings.

        Raises
        ------
        TypeError, ValueError
            If ``data`` has missing or unknown keys or invalid entries.
        """
        optional = ('options', 'default_options', 'model_solver', 'outcome',
                    'derivatives')
        _check_keys(data, ('method',), optional, 'SolverSettings')
        decoded = {key: (None if data.get(key) is None else
                         _decode_mapping(data[key],
                                         f'SolverSettings {key}'))
                   for key in optional}
        return cls(data['method'], **decoded)


