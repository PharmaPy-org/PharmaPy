"""Versioned, JSON-serializable provenance records for model calibration.

A ``CalibrationRecord`` stores everything needed to reload a parameter
estimation and rerun it: the observations as ``Experiment`` and
``Measurement`` objects of :mod:`PharmaPy.ParamEstim`, the data sources and
their sharing conditions, the transformations applied to the data, the
parameter names, order, units, bounds and fitted values, the model revision,
the optimizer settings and outcome, and stored model fields (states,
algebraic variables, quality attributes and measurement predictions) with an
explicit identity.

The records are an exchange format, not a second observation hierarchy:
``Experiment`` and ``Measurement`` remain the in-memory observation
objects, and a record serializes and reconstructs them exactly. An
unfitted template record, which shows the sections by example (``solver``,
``covariance`` and ``weight_matrix`` are null), is shipped with PharmaPy
(``template_text`` and ``load_template``).

Serialization contract
----------------------
* JSON is standard: ``NaN`` and infinities are never emitted. A missing
  observation (``NaN``) is written as ``null`` and read back as ``NaN``.
* Floats are written with Python's shortest round-trip representation, so
  every value is read back bit for bit.
* Ordered collections (experiments, measurements, parameters, sources,
  transformations, fields) are JSON arrays in declared order; nothing is
  sorted.
* Callback arguments and option mappings may hold ``None``, ``bool``,
  ``int``, finite ``float``, ``str``, lists, dicts with str keys, tuples,
  NumPy scalars and plain ``numpy.ndarray`` objects of boolean, integer or
  at most 64-bit floating dtype. Tuples and NumPy values are written as
  objects tagged by the reserved key ``'__type__'``, with the dtype string
  including byte order (e.g. ``'>f8'``), so their types are restored
  exactly. Any other object, including complex and extended-precision
  values and ndarray subclasses such as ``numpy.matrix`` or masked arrays,
  raises ``TypeError`` naming its location, as do structured dtypes and
  dtypes carrying metadata. Reading is strict: entries must have the JSON
  type of their dtype and round-trip through it. The dtype, byte order
  included, and the values round-trip exactly; platform aliases such as
  ``numpy.longlong`` come back as the equivalent sized type (e.g.
  ``numpy.int64``), which has the same dtype.
* Files are written atomically as UTF-8 without a byte-order mark; a
  byte-order mark is tolerated when reading.

No unit conversion is performed anywhere in this module: unit and basis
labels document the stored numbers, which must already be in the units and
physical basis of the model.
"""

