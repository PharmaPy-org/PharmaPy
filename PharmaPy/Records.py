def _identity_sequence(identities, label: str) -> tuple:
    """Validate a sequence of field identities.

    Parameters
    ----------
    identities : sequence of FieldIdentity
        Identities in column order.
    label : str
        Input name used in error messages.

    Returns
    -------
    tuple of FieldIdentity
        Identities in the given order.

    Raises
    ------
    TypeError
        If an entry is not a ``FieldIdentity``.
    ValueError
        If names repeat.
    """
    identities = _sequence(identities, label)
    for identity in identities:
        if not isinstance(identity, FieldIdentity):
            raise TypeError(f"{label} entries must be FieldIdentity; got "
                            f"{type(identity).__name__}")
    _unique_names([identity.name for identity in identities], label)
    return identities


def fields_from_array(x, array, identities: Sequence, *, x_units: str = 's',
                      experiment: Optional[str] = None) -> tuple:
    """Split a legacy state array into identified field records.

    Parameters
    ----------
    x : array_like
        Independent-variable samples, shape ``(n,)``, in ``x_units``.
    array : array_like
        Legacy state array, shape ``(n, k)`` with one row per sample and
        one column per field in ``identities`` order; a one-dimensional
        array of shape ``(n,)`` is a single field. Each column is in the
        units of its identity.
    identities : sequence of FieldIdentity
        One identity per column, with distinct names.
    x_units : str, optional
        Units of ``x``. The default is ``'s'``.
    experiment : str, optional
        Experiment the fields belong to.

    Returns
    -------
    tuple of FieldRecord
        One record per column, in column order, holding float64 copies.

    Raises
    ------
    TypeError
        If ``identities`` holds a non-``FieldIdentity`` or ``array`` is not
        real numeric.
    ValueError
        If ``array`` has more than two dimensions, its row count differs
        from ``x`` or its column count from ``identities``, or names
        repeat.
    """
    identities = _identity_sequence(identities, 'identities')
    try:
        is_complex = np.iscomplexobj(np.asarray(array))
    except (TypeError, ValueError):
        is_complex = False  # reported by the float conversion below
    if is_complex:
        raise TypeError("array must be real; got complex values")
    try:
        array = np.array(array, dtype=np.float64)  # [column units]
    except (TypeError, ValueError) as error:
        raise TypeError(f"array must be numeric; {error}") from error
    if array.ndim == 1:
        array = array[:, np.newaxis]  # [column units]
    if array.ndim != 2:
        raise ValueError("array must be one- or two-dimensional (samples x "
                         f"fields); got shape {array.shape}")
    if array.shape[1] != len(identities):
        raise ValueError(
            f"array has {array.shape[1]} columns but {len(identities)} "
            f"identities were given: {[i.name for i in identities]!r}")
    return tuple(FieldRecord(identity, x, array[:, column], x_units=x_units,
                             experiment=experiment)
                 for column, identity in enumerate(identities))


def _select_shared(fields, names, experiment=_UNSET,
                   kind: Optional[str] = None) -> list:
    """Select field records that share one grid and experiment.

    Parameters
    ----------
    fields : sequence of FieldRecord
        Field records; after filtering, their names must be distinct.
    names : sequence of str or None
        Names to select, in the requested order; None selects every
        remaining field in the given order.
    experiment : str or None, optional
        Keep only fields of this experiment (None keeps fields without an
        experiment). By default no experiment filter is applied.
    kind : str, optional
        Keep only fields of this kind (one of ``FIELD_KINDS``). The default
        None applies no kind filter.

    Returns
    -------
    list of FieldRecord
        Selected records in the requested order.

    Raises
    ------
    TypeError
        If an entry is not a ``FieldRecord`` or ``names`` is not a list or
        tuple.
    ValueError
        If ``kind`` is unknown, no field passes the filters, ``names`` is
        empty, names repeat after filtering or are unknown, or the selected
        fields differ in ``experiment``, ``x`` or ``x_units``.
    """
    fields = _sequence(fields, 'fields')
    for field in fields:
        if not isinstance(field, FieldRecord):
            raise TypeError("fields entries must be FieldRecord; got "
                            f"{type(field).__name__}")
    if kind is not None:
        _choice(kind, FIELD_KINDS, 'kind')
        fields = [field for field in fields if field.identity.kind == kind]
    if experiment is not _UNSET:
        fields = [field for field in fields
                  if field.experiment == experiment]
    if not fields:
        raise ValueError("fields must contain at least one FieldRecord "
                         "that passes the experiment and kind filters")
    names_seen = [field.name for field in fields]
    repeated = list(dict.fromkeys(name for name in names_seen
                                  if names_seen.count(name) > 1))
    if repeated:
        raise ValueError(
            f"fields names must be unique; repeated {repeated!r}. Select "
            "one experiment and kind with the experiment= and kind= "
            "filters")
    by_name = {field.name: field for field in fields}
    names = list(by_name) if names is None else list(
        _sequence(names, 'names'))
    if not names:
        raise ValueError("names must contain at least one field name")
    _unique_names(names, 'names')
    unknown = [name for name in names if name not in by_name]
    if unknown:
        raise ValueError(f"names {unknown!r} are not among the fields "
                         f"{list(by_name)!r}")
    selected = [by_name[name] for name in names]
    reference = selected[0]
    for field in selected:
        if field.experiment != reference.experiment:
            raise ValueError(
                f"Fields {reference.name!r} and {field.name!r} belong to "
                f"different experiments ({reference.experiment!r} and "
                f"{field.experiment!r}); convert each experiment separately")
        if (field.x_units != reference.x_units
                or not np.array_equal(field.x, reference.x)):
            raise ValueError(
                f"Fields {reference.name!r} and {field.name!r} have "
                "different x samples or x_units; legacy arrays and "
                "dictionaries need one shared grid")
    return selected


def fields_to_array(fields: Sequence, names: Optional[Sequence] = None, *,
                    experiment=_UNSET,
                    kind: Optional[str] = None) -> tuple:
    """Assemble one-dimensional field records into a legacy state array.

    Inverse of ``fields_from_array``.

    Parameters
    ----------
    fields : sequence of FieldRecord
        Records with distinct names.
    names : sequence of str, optional
        Field names in the requested column order; at least one. The
        default is the order of ``fields``. The selected fields must have
        one-dimensional values and share ``experiment``, ``x`` and
        ``x_units``.
    experiment : str or None, optional
        Use only fields of this experiment (None: fields without an
        experiment); by default all fields are used.
    kind : str, optional
        Use only fields of this kind, e.g. ``'measurement_prediction'``;
        by default all kinds are used.

    Returns
    -------
    x : numpy.ndarray
        New float64 samples, shape ``(n,)``, in the shared ``x_units``.
    array : numpy.ndarray
        New float64 array, shape ``(n, len(names))``; column ``j`` holds
        field ``names[j]`` in its own units, NaN where missing.

    Raises
    ------
    TypeError
        If an entry is not a ``FieldRecord``.
    ValueError
        If no field passes the filters, ``names`` is empty, names repeat
        after filtering or are unknown, a selected field is
        two-dimensional, or the selected fields differ in ``experiment``,
        ``x`` or ``x_units``.
    """
    selected = _select_shared(fields, names, experiment, kind)
    for field in selected:
        if field.values.ndim != 1:
            raise ValueError(f"Field {field.name!r} has two-dimensional "
                             "values; use fields_to_mapping instead")
    return (np.array(selected[0].x),
            np.column_stack([field.values for field in selected]))


def fields_from_mapping(x, mapping: Mapping, identities, *,
                        x_units: str = 's',
                        experiment: Optional[str] = None,
                        columns: Optional[Mapping] = None) -> tuple:
    """Convert a legacy ``{name: array}`` dictionary into field records.

    Parameters
    ----------
    x : array_like
        Independent-variable samples, shape ``(n,)``, in ``x_units``.
    mapping : Mapping[str, array_like]
        Field values by name, each of shape ``(n,)`` or ``(n, m)`` in the
        units of its identity. Its iteration order is the record order.
    identities : Mapping[str, FieldIdentity] or sequence of FieldIdentity
        Identities with exactly the names of ``mapping``; a mapping must be
        keyed by each identity's name.
    x_units : str, optional
        Units of ``x``. The default is ``'s'``.
    experiment : str, optional
        Experiment the fields belong to.
    columns : Mapping[str, sequence of str], optional
        Component labels of each two-dimensional entry, by name.

    Returns
    -------
    tuple of FieldRecord
        One record per entry, in ``mapping`` order.

    Raises
    ------
    TypeError
        If ``mapping`` is not a mapping or an identity is not a
        ``FieldIdentity``.
    ValueError
        If names are missing, unexpected or repeated, a mapping key differs
        from its identity's name, or an entry is invalid.
    """
    if not isinstance(mapping, Mapping):
        raise TypeError("mapping must be a mapping of field names to arrays; "
                        f"got {type(mapping).__name__}")
    if isinstance(identities, Mapping):
        for key, identity in identities.items():
            if not isinstance(identity, FieldIdentity):
                raise TypeError("identities values must be FieldIdentity; "
                                f"got {type(identity).__name__}")
            if key != identity.name:
                raise ValueError(f"identities key {key!r} differs from its "
                                 f"identity name {identity.name!r}")
        by_name = dict(identities)
    else:
        by_name = {identity.name: identity for identity in
                   _identity_sequence(identities, 'identities')}
    columns = {} if columns is None else dict(columns)
    missing = [name for name in by_name if name not in mapping]
    unexpected = [name for name in mapping if name not in by_name]
    stray = [name for name in columns if name not in mapping]
    if missing or unexpected or stray:
        raise ValueError(
            f"mapping lacks identified fields {missing!r}, holds fields "
            f"without identity {unexpected!r}, and columns names unknown "
            f"fields {stray!r}")
    return tuple(FieldRecord(by_name[name], x, values, x_units=x_units,
                             columns=columns.get(name),
                             experiment=experiment)
                 for name, values in mapping.items())


def fields_to_mapping(fields: Sequence, *, experiment=_UNSET,
                      kind: Optional[str] = None) -> tuple:
    """Convert field records into a legacy ``{name: array}`` dictionary.

    Inverse of ``fields_from_mapping``.

    Parameters
    ----------
    fields : sequence of FieldRecord
        Records; after filtering, with distinct names that share
        ``experiment``, ``x`` and ``x_units``.
    experiment : str or None, optional
        Use only fields of this experiment (None: fields without an
        experiment); by default all fields are used.
    kind : str, optional
        Use only fields of this kind; by default all kinds are used.

    Returns
    -------
    x : numpy.ndarray
        New float64 samples, shape ``(n,)``, in the shared ``x_units``.
    mapping : dict
        Field name to a new writable float64 copy of its values, shape
        ``(n,)`` or ``(n, m)``, in the order of ``fields``.

    Raises
    ------
    TypeError
        If an entry is not a ``FieldRecord``.
    ValueError
        If no field passes the filters, names repeat after filtering, or
        the fields differ in ``experiment``, ``x`` or ``x_units``.
    """
    selected = _select_shared(fields, None, experiment, kind)
    return (np.array(selected[0].x),
            {field.name: np.array(field.values) for field in selected})


