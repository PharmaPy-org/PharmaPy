def _real_matrix(matrix, label: str) -> np.ndarray:
    """Convert a numeric matrix to float64, rejecting other value types.

    Parameters
    ----------
    matrix : array_like or pandas.DataFrame
        Real numeric values; units are preserved.
    label : str
        Input name used in error messages.

    Returns
    -------
    numpy.ndarray
        New float64 array.

    Raises
    ------
    TypeError
        If the values are complex, boolean or non-numeric.
    """
    values = (matrix.to_numpy() if isinstance(matrix, pd.DataFrame)
              else np.asarray(matrix))
    if values.dtype.kind == 'O':
        try:
            values = np.array(values.tolist())
        except (TypeError, ValueError) as error:
            raise TypeError(f"{label} must hold real numbers; {error}"
                            ) from error
    if values.dtype.kind == 'c':
        raise TypeError(f"{label} must hold real numbers; got complex "
                        "values")
    if values.dtype.kind not in 'iuf':
        raise TypeError(f"{label} must hold real numbers; got dtype "
                        f"{values.dtype}")
    return np.array(values, dtype=np.float64)


def _weight_matrix_array(weight_matrix, names: list) -> np.ndarray:
    """Validate a labelled weight matrix as ``ParameterEstimation`` reads it.

    Parameters
    ----------
    weight_matrix : pandas.DataFrame
        Measurement-error covariance labelled by measurement names in any
        order; entry ``(i, j)`` in the product of the units of
        measurements ``i`` and ``j``. Only its lower triangle (in the
        caller's index order) is read.
    names : list of str
        Measurement column names in column order.

    Returns
    -------
    numpy.ndarray
        Effective symmetric covariance, shape ``(n, n)`` in ``names``
        order, built from the lower triangle by
        ``ParamEstim._labelled_weight_matrix``.

    Raises
    ------
    TypeError
        If ``weight_matrix`` is not a DataFrame or holds complex or
        non-numeric values.
    ValueError
        If its labels are not exactly ``names``, the effective covariance
        is not finite, or it is not positive definite.
    """
    if not isinstance(weight_matrix, pd.DataFrame):
        raise TypeError("weight_matrix must be a pandas.DataFrame labelled "
                        "by measurement names; got "
                        f"{type(weight_matrix).__name__}")
    _real_matrix(weight_matrix, 'weight_matrix')
    symmetric = _labelled_weight_matrix(weight_matrix, names)  # [u_i*u_j]
    if not np.isfinite(symmetric).all():
        raise ValueError("weight_matrix must be finite in its lower "
                         "triangle, which ParameterEstimation reads")
    try:
        np.linalg.cholesky(symmetric)
    except np.linalg.LinAlgError as error:
        raise ValueError("weight_matrix must be a positive-definite "
                         "covariance") from error
    return symmetric


def _effective_options(options: Mapping, method: str) -> dict:
    """Return the options left in ``optim_options``, as recordable entries.

    Parameters
    ----------
    options : Mapping
        ``ParameterEstimation.optim_options`` after ``optimize_fn``: the
        effective options of the fit, i.e. the private copy that
        ``optimize_fn`` passed to the solver (issue #476). For IPOPT fits
        cyipopt has rewritten that copy in place, with bytes keys and its
        own default entries, some with bytes string values, added.
    method : {'LM', 'IPOPT'}
        Optimization method of the fit.

    Returns
    -------
    dict
        Options with bytes keys and bytes values decoded as UTF-8, without
        the entries ``optimize_fn`` injects itself (``_INJECTED_OPTIONS``).
        For IPOPT these are the caller's options plus the entries cyipopt
        1.7 writes into the dict when they are missing (``tol``,
        ``mu_strategy`` and, without a Hessian, ``hessian_approximation``;
        ``print_level`` is injected and omitted here). Passing them back
        sets those options again; Ipopt's native defaults, e.g.
        ``max_iter`` and ``acceptable_tol``, are not in the dict and are
        not recorded.

    Raises
    ------
    ValueError
        If a bytes key or value is not valid UTF-8, or a key appears both as
        str and as bytes.
    """
    def text(value, label: str) -> str:
        """Decode a bytes option entry.

        Parameters
        ----------
        value : bytes
            Option key or value.
        label : str
            Description used in error messages.

        Returns
        -------
        str
            UTF-8 decoded text.

        Raises
        ------
        ValueError
            If ``value`` is not valid UTF-8.
        """
        try:
            return value.decode('utf-8')
        except UnicodeDecodeError as error:
            raise ValueError(f"optim_options {label} {value!r} is not UTF-8 "
                             "text") from error

    effective = {}
    for key, value in options.items():
        name = text(key, 'key') if isinstance(key, bytes) else key
        if name in effective:
            raise ValueError(f"optim_options holds {name!r} both as str and "
                             "as bytes")
        if isinstance(value, bytes):
            value = text(value, f'value of {name!r}')
        effective[name] = value
    return {key: value for key, value in effective.items()
            if key not in _INJECTED_OPTIONS[method]}


def _default_options(method: str, given: Mapping) -> Optional[dict]:
    """Return the optimizer defaults in force for the options not given.

    Parameters
    ----------
    method : {'LM', 'IPOPT'}
        Optimization method of the fit.
    given : Mapping[str, object]
        Options the caller set, as returned by ``_effective_options``.

    Returns
    -------
    dict or None
        For LM, the keyword defaults of ``levenberg_marquardt`` read from
        its signature, so that they cannot drift from the code that ran
        the fit, in signature order: every parameter with a default except
        ``_LM_CALL_PARAMETERS``, the entries ``optimize_fn`` injects
        (``_INJECTED_OPTIONS``) and the keys of ``given``. For IPOPT, None:
        ``given`` holds the caller's options and the entries cyipopt writes
        into the dict (see ``_effective_options``); Ipopt's native
        defaults, e.g. ``max_iter`` and ``acceptable_tol``, are not
        available there and are not recorded, which None states.

    Notes
    -----
    The stopping criteria are the defaults issue #483 asks to record. In
    ``levenberg_marquardt``, with residuals ``r`` [residual units] (``[-]``
    when the measurements declare uncertainties), Jacobian ``J`` [residual
    units / parameter units] of shape ``(n_parameters, n_residuals)`` and
    gradient ``b = J @ r``:

    * ``max_fun_eval`` [-]: maximum number of model evaluations;
    * ``eps_1`` [residual units**2 / parameter units]: stop when
      ``norm(b) < eps_1`` after an accepted step;
    * ``eps_2`` [-]: stop when ``norm(step) < eps_2 * norm(x)``;
    * ``tol_fun`` [residual units]: stop when ``norm(r) < tol_fun``.

    With parameters of different units these norms mix units, as in
    ``levenberg_marquardt`` itself. ``fletcher_modif``, ``mu`` and
    ``d_diag`` are recorded too, because they change the iterates. The
    damping term is ``mu * D.T @ D`` with ``D = diag(d_diag)``. With
    ``d_diag=None``, ``fletcher_modif=False`` uses unit scaling (``D`` the
    identity), so ``mu`` is in [residual units**2 / parameter units**2];
    ``fletcher_modif=True`` uses Fletcher's Jacobian-based scaling, which
    starts every entry of ``D`` at the largest parameter row norm
    ``max(norm(J, axis=1))`` and, after each accepted step, replaces an
    entry by its parameter's current row norm when that is larger; ``D``
    then carries Jacobian units and ``mu`` is [-]. ``mu=None`` selects the
    initial damping
    ``1e-2 * max(diag(J @ J.T))`` after Nielsen (1999). Recording None
    states that the rule, not a caller value, was used; passing it back
    is identical to omitting it, and a release that changes such a
    default to a number shows up as a difference.
    """
    if method != 'LM':
        return None
    skipped = set(_LM_CALL_PARAMETERS) | set(_INJECTED_OPTIONS['LM'])
    return {name: parameter.default for name, parameter in
            inspect.signature(levenberg_marquardt).parameters.items()
            if parameter.default is not inspect.Parameter.empty
            and name not in skipped and name not in given}


def _same_value(first, second) -> bool:
    """Compare two callback values exactly through their record encoding.

    Parameters
    ----------
    first, second : object
        Values to compare.

    Returns
    -------
    bool
        True if both encode to the same JSON text: the same Python types
        (``True``, ``1`` and ``1.0`` differ; tuples and lists differ), NumPy
        dtypes including byte order, shapes, values (``-0.0`` and ``0.0``
        differ) and dict insertion order. Values that cannot be encoded are
        equal only if they are the same object.
    """
    try:
        encoded = [_encode_value(value, 'value') for value in (first, second)]
    except (TypeError, ValueError):
        return first is second
    return json.dumps(encoded[0]) == json.dumps(encoded[1])


def _check_callback_inputs(name: str, experiment: Experiment, args,
                           kwargs) -> list:
    """Compare an experiment's callback inputs with an estimator's.

    Parameters
    ----------
    name : str
        Experiment name used in error messages.
    experiment : Experiment
        Experiment to be recorded.
    args : tuple
        Positional callback arguments the estimator passes for it.
    kwargs : Mapping
        Callback keywords the estimator passes for it.

    Returns
    -------
    list of str
        Keywords the estimator passes beyond the experiment's own, all of
        them ``SimulationExec`` wrapper keywords, in the estimator's order.

    Raises
    ------
    ValueError
        If the positional arguments differ, a keyword of the experiment is
        missing, differs or comes in another order, or the estimator passes
        a keyword the experiment lacks other than the ``SimulationExec``
        wrapper keywords ``modify_phase``, ``modify_controls`` and
        ``run_args``.

    Notes
    -----
    Values are compared with ``_same_value``, i.e. exactly in type, dtype,
    shape, value and order. ``SimulationExec.SetParamEstimation`` rebuilds
    each ``Experiment`` with the same ``args`` and appends those wrapper
    keywords unless the experiment binds them itself, so a correct capture
    of a ``SimulationExec`` fit passes this check.
    """
    from PharmaPy.SimExec import WRAPPER_ARGUMENTS

    if not _same_value(tuple(args), tuple(experiment.args)):
        raise ValueError(
            f"Experiment {name!r}: the estimator's positional callback "
            f"arguments {tuple(args)!r} differ from the experiment's args "
            f"{tuple(experiment.args)!r}")
    for key, value in experiment.kwargs.items():
        if key not in kwargs or not _same_value(kwargs[key], value):
            raise ValueError(
                f"Experiment {name!r}: the estimator's callback keyword "
                f"{key!r} differs from the experiment's kwargs")
    own = [key for key in kwargs if key in experiment.kwargs]
    if own != list(experiment.kwargs):
        raise ValueError(
            f"Experiment {name!r}: the estimator's callback keywords come in "
            f"the order {own!r}, the experiment's in "
            f"{list(experiment.kwargs)!r}")
    extra = [key for key in kwargs if key not in experiment.kwargs]
    unknown = [key for key in extra if key not in WRAPPER_ARGUMENTS]
    if unknown:
        raise ValueError(
            f"Experiment {name!r}: the estimator passes callback keywords "
            f"{unknown!r} that the experiment does not define")
    return extra


def _check_estimator_data(estimator: ParameterEstimation,
                          experiments: Mapping) -> dict:
    """Verify that an estimator was compiled from the given experiments.

    Parameters
    ----------
    estimator : ParameterEstimation
        Estimator built from ``experiments`` directly or through
        ``SimulationExec.SetParamEstimation``.
    experiments : Mapping[str, Experiment]
        Experiments to be recorded, in estimator order.

    Returns
    -------
    dict
        Experiment name to a new ``Experiment`` with the effective callback
        inputs: the same measurements and ``args``, and the experiment's
        keywords (in their order) followed by the ``SimulationExec`` wrapper
        keywords the estimator adds, with the estimator's values.

    Raises
    ------
    ValueError
        Naming the experiment and quantity, if the measurement columns,
        resolved model-output fields, model grids ``x_model``,
        observations ``y_data`` (NaN-aware, including dtype), measurement
        standard deviations or callback inputs differ from those obtained
        by compiling ``experiments`` with ``_compile_experiments``.
    TypeError
        If a wrapper keyword value cannot be recorded (see the record
        codec), naming the experiment and keyword; ValueError instead for
        a non-finite value.
    """
    if getattr(estimator, '_measurement_names', None) is None:
        raise ValueError("The estimator was not built from Experiment "
                         "objects; records capture Experiment-based fits")
    compiled = _compile_experiments(dict(experiments),
                                    estimator.output_names)
    if list(estimator._measurement_names) != compiled.measurement_names:
        raise ValueError(
            f"The estimator measurement columns "
            f"{list(estimator._measurement_names)!r} differ from the "
            f"experiments' {compiled.measurement_names!r}")
    if list(estimator._measured_fields) != compiled.fields:
        raise ValueError(
            f"The estimator model-output fields "
            f"{list(estimator._measured_fields)!r} differ from the "
            f"experiments' {compiled.fields!r}")
    if (estimator._residual_std is None) != (compiled.residual_std is None):
        raise ValueError("The estimator and the experiments differ in "
                         "whether measurement uncertainties are declared")

    def same(actual, expected) -> bool:
        """Compare two arrays exactly, NaN entries included.

        Parameters
        ----------
        actual, expected : array_like
            Arrays to compare.

        Returns
        -------
        bool
            True if dtype, shape and every entry agree.
        """
        actual, expected = np.asarray(actual), np.asarray(expected)
        return (actual.dtype == expected.dtype
                and actual.shape == expected.shape
                and np.array_equal(actual, expected,
                                   equal_nan=actual.dtype.kind in 'fc'))

    effective = {}
    for index, name in enumerate(experiments):
        checks = [('model grid x_model', estimator.x_model[index],
                   compiled.x_model[index]),
                  ('observations y_data', estimator.y_data[index],
                   compiled.y_data[index])]
        if compiled.residual_std is not None:
            checks.append(('measurement standard deviations',
                           estimator._residual_std[index],
                           compiled.residual_std[index]))
        for quantity, actual, expected in checks:
            if not same(actual, expected):
                raise ValueError(f"Experiment {name!r}: the estimator's "
                                 f"{quantity} differ from the experiment's")
        experiment = experiments[name]
        kwargs = estimator.kwargs_fun[index]
        extra = _check_callback_inputs(name, experiment,
                                       estimator.args_fun[index], kwargs)
        for key in extra:
            path = f'experiments[{name!r}].kwargs[{key!r}]'
            try:
                _encode_value(kwargs[key], path)
            except (TypeError, ValueError) as error:
                raise type(error)(
                    f"Experiment {name!r}: SimulationExec wrapper keyword "
                    f"{key!r} holds a value that a record cannot hold "
                    f"({error}). Records need serializable phase and "
                    "control modifiers and run_args (numbers, str, lists, "
                    "dicts, tuples, NumPy values), not callables or model "
                    "objects") from error
        effective[name] = Experiment(
            dict(experiment.measurements), args=experiment.args,
            kwargs={**dict(experiment.kwargs),
                    **{key: kwargs[key] for key in extra}})
    return effective


def _declared_metadata(experiments: Mapping) -> tuple:
    """Merge the declared labels of measurements across experiments.

    Parameters
    ----------
    experiments : Mapping[str, Experiment]
        Experiments in order.

    Returns
    -------
    units : dict
        Measurement name -> first declared (non-None) units label.
    basis : dict
        Measurement name -> first declared basis label, or None.
    x_units : str or None
        First declared independent-variable units label.

    Notes
    -----
    Mirrors the declared-label map of ``ParamEstim._compile_experiments``,
    which accepts None (undeclared) next to a declared label and rejects
    two different declared labels.
    """
    units, basis, x_units = {}, {}, None
    for experiment in experiments.values():
        for name, measurement in experiment.measurements.items():
            if units.get(name) is None:
                units[name] = measurement.units
            if basis.get(name) is None:
                basis[name] = measurement.basis
            if x_units is None:
                x_units = measurement.x_units
    return units, basis, x_units


class CalibrationRecord(_ImmutableRecord):
    """Provenance record of one parameter-estimation case.

    The record holds the observations as ``Experiment`` objects together
    with their provenance, the parameters, the optimizer settings and
    stored model fields, and serializes them to versioned JSON (see the
    module docstring). ``estimation_inputs`` and ``optimizer_inputs``
    rebuild a ``ParameterEstimation`` and rerun its fit.

    Parameters
    ----------
    case : str
        Identifier of the calibration case.
    experiments : Mapping[str, Experiment]
        Named experiments; insertion order is the experiment order. Every
        measurement must declare ``units`` and ``x_units``; callback
        arguments must be serializable (see the module docstring). They
        are validated as ``ParameterEstimation`` compiles them, so
        contradictory units or bases for one measurement name or field,
        inconsistent ``x_units``, uncertainties declared by only some
        measurements and unresolvable fields are rejected.
    parameters : sequence of ParameterRecord
        At least one parameter, in model-callback order, with distinct
        names.
    sources : sequence of DataSource
        At least one source, with distinct names.
    model : ModelRevision
        Calibrated model.
    description : str, optional
        Free-text description.
    output_names : sequence of str, optional
        ``output_names`` of ``ParameterEstimation``: names of the model
        callback output columns, needed by str measurement fields.
    transformations : sequence of Transformation, optional
        Data transformations in application order. Their ``source`` must
        name a source and their ``fields`` measurement names or stored
        field names.
    solver : SolverSettings, optional
        Optimizer settings and outcome; None before fitting.
    fields : sequence of FieldRecord, optional
        Stored states, algebraic variables, quality attributes and
        measurement predictions. A field's ``experiment`` must name a
        record experiment; (experiment, kind, name) triples must be
        distinct, so a state and a measurement prediction may share a
        name. A ``'measurement_prediction'`` must name its experiment and a
        measurement of the record, with that measurement's declared units
        and basis (the first declared across experiments) and its
        experiment's ``x_units``.
    weight_matrix : pandas.DataFrame, optional
        Measurement-error covariance labelled by exactly the measurement
        names, as accepted by ``ParameterEstimation``: entry ``(i, j)`` in
        the product of the units of measurements ``i`` and ``j``, only the
        lower triangle read. It is stored as the effective symmetric,
        positive-definite covariance in measurement-column order. Not
        allowed when measurements declare uncertainties.
    covariance : array_like, optional
        Parameter covariance, shape ``(k, k)`` for the ``k`` optimized
        parameters in record order, as returned by
        ``ParameterEstimation.get_covariance``. Entry ``(i, j)`` has the
        product of the units of parameters ``i`` and ``j`` when the
        weighted residuals are dimensionless (declared uncertainties, or a
        ``weight_matrix`` of error covariances in squared measurement
        units), for both forms. With the default identity weighting this
        holds for the ``include_mse=True`` form only if every residual has
        the same physical unit; the unscaled form is then additionally
        divided by that unit squared. With identity weighting of residuals
        in different units neither form is a physical covariance. It
        requires fitted values.
    covariance_include_mse : bool, optional
        Form of ``covariance``: True for ``get_covariance(include_mse=True)``
        (scaled by the residual mean square), False for the unscaled form.
        Required with ``covariance`` and not allowed without it.

    Raises
    ------
    TypeError
        If an entry has the wrong type, values are complex or non-numeric,
        or an entry cannot be serialized.
    ValueError
        If ``experiments``, ``parameters`` or ``sources`` is empty, names
        repeat, the experiments are inconsistent, a cross-reference is
        dangling, fitted values are given for only some optimized
        parameters, or a matrix has the wrong labels, shape or values.

    Notes
    -----
    The record keeps the serialized form of the experiments: ``experiments``
    returns new ``Experiment`` objects on every access, so changing callback
    arguments of returned objects or the caller's original objects never
    changes the record.
    """

    __slots__ = ('_case', '_description', '_experiments', '_output_names',
                 '_parameters', '_sources', '_transformations', '_model',
                 '_solver', '_fields', '_weight_matrix', '_covariance',
                 '_covariance_include_mse')

    def __init__(self, case: str, experiments: Mapping,
                 parameters: Sequence, sources: Sequence,
                 model: ModelRevision, *, description: Optional[str] = None,
                 output_names: Optional[Sequence] = None,
                 transformations: Sequence = (),
                 solver: Optional[SolverSettings] = None,
                 fields: Sequence = (), weight_matrix=None,
                 covariance=None,
                 covariance_include_mse: Optional[bool] = None) -> None:
        """Validate and store the record.

        Parameters
        ----------
        case, experiments, parameters, sources, model, description, \
output_names, transformations, solver, fields, weight_matrix, covariance, \
covariance_include_mse
            See the class docstring.

        Raises
        ------
        TypeError, ValueError
            See the class docstring.
        """
        self._set('_case', _text(case, 'CalibrationRecord case'))
        self._set('_description', _text(description,
                                        'CalibrationRecord description',
                                        optional=True))

        if not isinstance(experiments, Mapping):
            raise TypeError("experiments must be a mapping of experiment "
                            "names to Experiment objects; got "
                            f"{type(experiments).__name__}")
        if not experiments:
            raise ValueError("experiments must hold at least one Experiment")
        encoded = {}
        for name, experiment in experiments.items():
            _text(name, 'Experiment name')
            encoded[name] = _encode_experiment(name, experiment)
        self._set('_experiments', encoded)
        output_names = _validate_output_names(output_names)
        self._set('_output_names', output_names)
        # The same compile path as ParameterEstimation, so every stored
        # record can be rebuilt.
        compiled = _compile_experiments(dict(experiments), output_names)
        measurement_names = compiled.measurement_names

        parameters = _sequence(parameters, 'parameters')
        if not parameters:
            raise ValueError("parameters must hold at least one "
                             "ParameterRecord")
        for item in parameters:
            if not isinstance(item, ParameterRecord):
                raise TypeError("parameters entries must be ParameterRecord; "
                                f"got {type(item).__name__}")
        _unique_names([item.name for item in parameters], 'Parameter')
        optimized = [item for item in parameters if item.optimized]
        fitted = [item.fitted is not None for item in optimized]
        if any(fitted) and not all(fitted):
            raise ValueError(
                "Fitted values must be given for every optimized parameter "
                "or for none; missing for "
                f"{[i.name for i in optimized if i.fitted is None]!r}")
        self._set('_parameters', parameters)

        sources = _sequence(sources, 'sources')
        if not sources:
            raise ValueError("sources must hold at least one DataSource: "
                             "every calibration records where its data come "
                             "from and how they may be shared")
        for item in sources:
            if not isinstance(item, DataSource):
                raise TypeError("sources entries must be DataSource; got "
                                f"{type(item).__name__}")
        _unique_names([item.name for item in sources], 'DataSource')
        self._set('_sources', sources)

        if not isinstance(model, ModelRevision):
            raise TypeError("model must be a ModelRevision; got "
                            f"{type(model).__name__}")
        self._set('_model', model)
        if solver is not None and not isinstance(solver, SolverSettings):
            raise TypeError("solver must be a SolverSettings or None; got "
                            f"{type(solver).__name__}")
        self._set('_solver', solver)

        fields = _sequence(fields, 'fields')
        keys = []
        for field in fields:
            if not isinstance(field, FieldRecord):
                raise TypeError("fields entries must be FieldRecord; got "
                                f"{type(field).__name__}")
            if (field.experiment is not None
                    and field.experiment not in encoded):
                raise ValueError(
                    f"FieldRecord {field.name!r} names experiment "
                    f"{field.experiment!r}, which is not among "
                    f"{list(encoded)!r}")
            keys.append((field.experiment, field.identity.kind, field.name))
        _unique_names(keys, 'FieldRecord (experiment, kind, name)')
        units_by_name, basis_by_name, _ = _declared_metadata(experiments)
        for field in fields:
            if field.identity.kind != 'measurement_prediction':
                continue
            label = f"Measurement prediction {field.name!r}"
            if field.experiment is None:
                raise ValueError(f"{label} must name its experiment")
            if field.name not in measurement_names:
                raise ValueError(
                    f"{label} of experiment {field.experiment!r} names no "
                    f"measurement of the record {measurement_names!r}")
            declared = (units_by_name[field.name], basis_by_name[field.name])
            given = (field.identity.units, field.identity.basis)
            if given != declared:
                raise ValueError(
                    f"{label} of experiment {field.experiment!r} has units "
                    f"and basis {given!r}; the measurement declares "
                    f"{declared!r}")
            x_units = experiments[field.experiment].x_units
            if field.x_units != x_units:
                raise ValueError(
                    f"{label} of experiment {field.experiment!r} has x_units "
                    f"{field.x_units!r}; the experiment declares "
                    f"{x_units!r}")
        self._set('_fields', fields)

        source_names = [item.name for item in sources]
        known = set(measurement_names) | {field.name for field in fields}
        transformations = _sequence(transformations, 'transformations')
        for item in transformations:
            if not isinstance(item, Transformation):
                raise TypeError("transformations entries must be "
                                f"Transformation; got {type(item).__name__}")
            if item.source is not None and item.source not in source_names:
                raise ValueError(
                    f"Transformation {item.description!r} names source "
                    f"{item.source!r}, which is not among {source_names!r}")
            dangling = [name for name in item.fields if name not in known]
            if dangling:
                raise ValueError(
                    f"Transformation {item.description!r} names fields "
                    f"{dangling!r} that are neither measurements nor stored "
                    "fields of the record")
        self._set('_transformations', transformations)

        if weight_matrix is not None:
            if compiled.residual_std is not None:
                raise ValueError(
                    "weight_matrix must be None when measurements declare an "
                    "uncertainty; ParameterEstimation rejects both together")
            symmetric = _weight_matrix_array(
                weight_matrix, measurement_names)  # [u_i * u_j]
            weight_matrix = {'index': list(measurement_names),
                             'columns': list(measurement_names),
                             'values': _float_list(symmetric,
                                                   'weight_matrix')}
        self._set('_weight_matrix', weight_matrix)

        if covariance is None:
            if covariance_include_mse is not None:
                raise ValueError("covariance_include_mse requires a "
                                 "covariance")
        else:
            if not isinstance(covariance_include_mse, bool):
                raise TypeError(
                    "covariance_include_mse must be True or False with a "
                    "covariance, stating the get_covariance form; got "
                    f"{covariance_include_mse!r}")
            if not any(fitted):
                raise ValueError("covariance requires fitted values of the "
                                 "optimized parameters")
            covariance = _real_matrix(covariance,
                                      'covariance')  # [u_i * u_j]
            size = len(optimized)  # [-], number of optimized parameters
            if covariance.shape != (size, size):
                raise ValueError(
                    "covariance must be square with one row and column per "
                    f"optimized parameter ({size}); got shape "
                    f"{covariance.shape}")
            if not np.isfinite(covariance).all():
                raise ValueError("covariance must be finite")
            covariance = _frozen(covariance)  # [u_i * u_j]
        self._set('_covariance', covariance)
        self._set('_covariance_include_mse', covariance_include_mse)

    # ------------------------------------------------------------ accessors
    @property
    def case(self) -> str:
        """Calibration case identifier.

        Returns
        -------
        str
            Case identifier.
        """
        return self._case

    @property
    def description(self) -> Optional[str]:
        """Free-text description.

        Returns
        -------
        str or None
            Description, or None.
        """
        return self._description

    @property
    def experiments(self) -> dict:
        """Recorded experiments.

        Returns
        -------
        dict
            New dict of new ``Experiment`` objects in experiment order, on
            every access.
        """
        return {name: _decode_experiment(
                    {key: value for key, value in data.items()
                     if key != 'name'})
                for name, data in self._experiments.items()}

    @property
    def output_names(self) -> Optional[tuple]:
        """Names of the model callback output columns.

        Returns
        -------
        tuple of str or None
            Names, or None.
        """
        return self._output_names

    @property
    def parameters(self) -> tuple:
        """Parameters in model-callback order.

        Returns
        -------
        tuple of ParameterRecord
            Parameters.
        """
        return self._parameters

    @property
    def sources(self) -> tuple:
        """Data sources.

        Returns
        -------
        tuple of DataSource
            Sources in declared order.
        """
        return self._sources

    @property
    def transformations(self) -> tuple:
        """Data transformations in application order.

        Returns
        -------
        tuple of Transformation
            Transformations.
        """
        return self._transformations

    @property
    def model(self) -> ModelRevision:
        """Calibrated model.

        Returns
        -------
        ModelRevision
            Model identity and revision.
        """
        return self._model

    @property
    def solver(self) -> Optional[SolverSettings]:
        """Optimizer settings and outcome.

        Returns
        -------
        SolverSettings or None
            Settings, or None before fitting.
        """
        return self._solver

    @property
    def fields(self) -> tuple:
        """Stored model fields.

        Returns
        -------
        tuple of FieldRecord
            Fields in declared order.
        """
        return self._fields

    @property
    def weight_matrix(self) -> Optional[pd.DataFrame]:
        """Measurement-error covariance labelled by measurement names.

        Returns
        -------
        pandas.DataFrame or None
            New DataFrame on every access: the effective symmetric
            covariance in measurement-column order, entry ``(i, j)`` in the
            product of the units of measurements ``i`` and ``j``; or None.
        """
        if self._weight_matrix is None:
            return None
        return pd.DataFrame(
            _float_array(self._weight_matrix['values'], 'weight_matrix'),
            index=list(self._weight_matrix['index']),
            columns=list(self._weight_matrix['columns']))

    @property
    def covariance(self) -> Optional[np.ndarray]:
        """Parameter covariance of the optimized parameters.

        Returns
        -------
        numpy.ndarray or None
            Read-only, shape ``(k, k)`` in optimized-parameter order, in
            the units described in the class docstring; or None.
        """
        return self._covariance

    @property
    def covariance_include_mse(self) -> Optional[bool]:
        """Form of the recorded covariance.

        Returns
        -------
        bool or None
            The ``include_mse`` argument of
            ``ParameterEstimation.get_covariance`` that yields
            ``covariance``, or None without a covariance.
        """
        return self._covariance_include_mse

    @property
    def fitted_values(self) -> Optional[np.ndarray]:
        """Fitted values of the optimized parameters.

        Returns
        -------
        numpy.ndarray or None
            New float64 array, shape ``(k,)`` in optimized-parameter order
            (the order of ``optimize_fn``'s returned parameters), each in
            its parameter's units; None before fitting.
        """
        values = [item.fitted for item in self._parameters
                  if item.optimized]
        if not values or values[0] is None:
            return None
        return np.array(values, dtype=np.float64)

    # ------------------------------------------------------- serialization
    def to_dict(self) -> dict:
        """Serialize the record to JSON-compatible data.

        Returns
        -------
        dict
            New JSON object holding ``schema``, ``schema_version`` and every
            entry of the record; ordered collections are lists in declared
            order.
        """
        covariance = None
        if self._covariance is not None:
            covariance = {
                'parameters': [item.name for item in self._parameters
                               if item.optimized],
                'include_mse': self._covariance_include_mse,
                'values': _float_list(self._covariance, 'covariance')}
        return json.loads(json.dumps({
            'schema': RECORD_SCHEMA,
            'schema_version': RECORD_SCHEMA_VERSION,
            'case': self._case,
            'description': self._description,
            'model': self._model.to_dict(),
            'sources': [item.to_dict() for item in self._sources],
            'transformations': [item.to_dict()
                                for item in self._transformations],
            'output_names': (None if self._output_names is None
                             else list(self._output_names)),
            'parameters': [item.to_dict() for item in self._parameters],
            'experiments': list(self._experiments.values()),
            'weight_matrix': self._weight_matrix,
            'solver': (None if self._solver is None
                       else self._solver.to_dict()),
            'covariance': covariance,
            'fields': [item.to_dict() for item in self._fields],
        }, allow_nan=False))

    @classmethod
    def from_dict(cls, data: dict) -> 'CalibrationRecord':
        """Reconstruct a record written by ``to_dict``.

        Parameters
        ----------
        data : dict
            JSON object. ``schema`` must be ``RECORD_SCHEMA`` and
            ``schema_version`` must be ``RECORD_SCHEMA_VERSION``; optional
            entries may be omitted, but collections that are present must
            be JSON arrays (not null).

        Returns
        -------
        CalibrationRecord
            New record.

        Raises
        ------
        TypeError, ValueError
            If the schema or version is not supported, keys are missing or
            unknown, or an entry is invalid.
        """
        if not isinstance(data, dict):
            raise TypeError("A calibration record must be a JSON object; "
                            f"got {type(data).__name__}")
        if data.get('schema') != RECORD_SCHEMA:
            raise ValueError(f"Not a calibration record: schema is "
                             f"{data.get('schema')!r}, expected "
                             f"{RECORD_SCHEMA!r}")
        version = data.get('schema_version')
        if type(version) is not int or version != RECORD_SCHEMA_VERSION:
            raise ValueError(
                f"Unsupported calibration record schema_version {version!r}; "
                f"this PharmaPy reads version {RECORD_SCHEMA_VERSION}")
        _check_keys(data, ('schema', 'schema_version', 'case', 'model',
                           'sources', 'parameters', 'experiments'),
                    ('description', 'transformations', 'output_names',
                     'weight_matrix', 'solver', 'covariance', 'fields'),
                    'CalibrationRecord')
        for key in ('sources', 'parameters', 'experiments',
                    'transformations', 'fields'):
            if key in data and type(data[key]) is not list:
                raise TypeError(f"CalibrationRecord {key!r} must be a JSON "
                                f"array; got {type(data[key]).__name__}")
        output_names = data.get('output_names')
        if output_names is not None and type(output_names) is not list:
            raise TypeError("CalibrationRecord 'output_names' must be a JSON "
                            "array or null; got "
                            f"{type(output_names).__name__}")

        experiments = {}
        for item in data['experiments']:
            if not isinstance(item, dict) or 'name' not in item:
                raise ValueError("Every experiment needs a 'name'")
            name = _text(item['name'], 'Experiment name')
            if name in experiments:
                raise ValueError(f"Experiment name {name!r} is repeated")
            experiments[name] = _decode_experiment(
                {key: value for key, value in item.items()
                 if key != 'name'})

        weight_matrix = data.get('weight_matrix')
        if weight_matrix is not None:
            _check_keys(weight_matrix, ('index', 'columns', 'values'), (),
                        'weight_matrix')
            for key in ('index', 'columns'):
                if type(weight_matrix[key]) is not list:
                    raise TypeError(
                        f"weight_matrix {key!r} must be a JSON array of "
                        "measurement names; got "
                        f"{type(weight_matrix[key]).__name__}")
            weight_matrix = pd.DataFrame(
                _float_array(weight_matrix['values'], 'weight_matrix'),
                index=weight_matrix['index'],
                columns=weight_matrix['columns'])

        parameters = [ParameterRecord.from_dict(item)
                      for item in data['parameters']]
        covariance = data.get('covariance')
        include_mse = None
        if covariance is not None:
            _check_keys(covariance, ('parameters', 'include_mse', 'values'),
                        (), 'covariance')
            optimized = [item.name for item in parameters if item.optimized]
            if covariance['parameters'] != optimized:
                raise ValueError(
                    f"covariance parameters {covariance['parameters']!r} "
                    f"must be the optimized parameters {optimized!r} in "
                    "record order")
            include_mse = covariance['include_mse']
            covariance = _float_array(covariance['values'], 'covariance')

        solver = data.get('solver')
        return cls(
            data['case'], experiments, parameters,
            [DataSource.from_dict(item) for item in data['sources']],
            ModelRevision.from_dict(data['model']),
            description=data.get('description'),
            output_names=data.get('output_names'),
            transformations=[Transformation.from_dict(item) for item in
                             data.get('transformations', [])],
            solver=(None if solver is None
                    else SolverSettings.from_dict(solver)),
            fields=[FieldRecord.from_dict(item)
                    for item in data.get('fields', [])],
            weight_matrix=weight_matrix, covariance=covariance,
            covariance_include_mse=include_mse)

    def to_json(self) -> str:
        """Serialize the record to standard JSON text.

        Returns
        -------
        str
            Indented JSON ending with a newline; never contains ``NaN`` or
            ``Infinity``.
        """
        return json.dumps(self.to_dict(), indent=JSON_INDENT,
                          allow_nan=False, ensure_ascii=False) + '\n'

    @classmethod
    def from_json(cls, text: str) -> 'CalibrationRecord':
        """Parse a record from JSON text.

        Parameters
        ----------
        text : str
            Standard JSON written by ``to_json``.

        Returns
        -------
        CalibrationRecord
            New record.

        Raises
        ------
        ValueError
            If ``text`` is not valid JSON, holds the non-standard constants
            ``NaN`` or ``Infinity``, repeats an object key, or is not a
            valid record.
        TypeError
            If an entry has the wrong JSON type.
        """
        def reject_constant(name: str):
            """Reject non-standard JSON constants.

            Parameters
            ----------
            name : str
                ``'NaN'``, ``'Infinity'`` or ``'-Infinity'``.

            Raises
            ------
            ValueError
                Always.
            """
            raise ValueError(
                f"Calibration records are standard JSON; found {name}. "
                "Write missing observations as null")

        def unique_keys(pairs: list) -> dict:
            """Build a JSON object, rejecting repeated keys.

            Parameters
            ----------
            pairs : list of tuple
                Key-value pairs in document order.

            Returns
            -------
            dict
                Object in document order.

            Raises
            ------
            ValueError
                If a key is repeated.
            """
            keys = [key for key, _ in pairs]
            _unique_names(keys, 'JSON object key')
            return dict(pairs)

        return cls.from_dict(json.loads(text, parse_constant=reject_constant,
                                        object_pairs_hook=unique_keys))

    def save(self, path) -> None:
        """Write the record to a UTF-8 JSON file atomically.

        The record is serialized completely before the file system is
        touched. The text is then written to a new, uniquely named file in
        the destination directory, created with ``open()``'s default
        permissions (``0o666`` minus the process umask, applied by the
        operating system), which replaces the destination with
        ``os.replace``. A failed save therefore leaves an existing file
        unchanged and removes the temporary file. An existing destination
        keeps its permission bits. A symbolic link is followed, so the file
        it points to is replaced and the link is kept.

        Parameters
        ----------
        path : str or os.PathLike
            Destination file; it is overwritten. The text is UTF-8 without
            a byte-order mark, with ``'\\n'`` line ends on every platform.

        Raises
        ------
        OSError
            If the temporary file cannot be written or moved into place.
        """
        data = self.to_json().encode('utf-8')
        target = os.path.realpath(os.fspath(path))
        directory, name = os.path.split(target)
        flags = (os.O_WRONLY | os.O_CREAT | os.O_EXCL
                 | getattr(os, 'O_BINARY', 0))  # binary mode on Windows
        while True:
            temporary = os.path.join(directory,
                                     f'.{name}.{uuid.uuid4().hex}.tmp')
            try:
                handle = os.open(temporary, flags, _NEW_FILE_MODE)
            except FileExistsError:
                continue  # name collision; draw another name
            break
        try:
            with os.fdopen(handle, 'wb') as file:
                file.write(data)
            if os.path.exists(target):
                os.chmod(temporary, stat.S_IMODE(os.stat(target).st_mode))
            os.replace(temporary, target)
        except BaseException:
            if os.path.exists(temporary):
                os.remove(temporary)
            raise

    @classmethod
    def load(cls, path) -> 'CalibrationRecord':
        """Read a record from a UTF-8 JSON file.

        Parameters
        ----------
        path : str or os.PathLike
            File written by ``save`` or a filled-in template; a UTF-8
            byte-order mark, as some editors write, is tolerated.

        Returns
        -------
        CalibrationRecord
            New record.

        Raises
        ------
        ValueError, TypeError
            See ``from_json``.
        """
        with open(path, encoding='utf-8-sig') as file:
            return cls.from_json(file.read())

    # ------------------------------------------------------ reload and rerun
    def estimation_inputs(self) -> dict:
        """Keyword arguments that rebuild the ``ParameterEstimation``.

        Returns
        -------
        dict
            New entries ``param_seed`` (float64 array of seeds, in
            parameter units and record order), ``x_data`` (new experiments
            mapping), ``optimize_flags`` (list of bool), ``name_params``
            (all parameter names), ``output_names`` (list or None) and
            ``weight_matrix`` (DataFrame or None), plus ``dx_finitediff``
            when the solver settings record a numeric finite-difference
            step (in parameter units). Use as
            ``ParameterEstimation(func, **record.estimation_inputs())``,
            adding a ``jac_fun`` or callable ``dx_finitediff`` that the
            original fit used (see ``SolverSettings.derivatives``); they
            are callables and cannot be recorded.
        """
        inputs = {
            'param_seed': np.array([item.seed for item in self._parameters],
                                   dtype=np.float64),  # [parameter units]
            'x_data': self.experiments,
            'optimize_flags': [item.optimized for item in self._parameters],
            'name_params': [item.name for item in self._parameters],
            'output_names': (None if self._output_names is None
                             else list(self._output_names)),
            'weight_matrix': self.weight_matrix,
        }
        derivatives = (None if self._solver is None
                       else self._solver.derivatives)
        if (derivatives is not None
                and not isinstance(derivatives['dx_finitediff'], str)):
            # [parameter units], numeric finite-difference step
            inputs['dx_finitediff'] = derivatives['dx_finitediff']
        return inputs

    def optimizer_inputs(self) -> dict:
        """Keyword arguments that rerun ``optimize_fn``.

        Returns
        -------
        dict
            ``method``, a new ``optim_options`` dict on every call, and
            ``bounds``: one ``(lower, upper)`` pair per optimized parameter
            in parameter units (None for an unbounded side), or None when no
            bound is declared. ``optim_options`` holds the recorded
            ``solver.default_options`` followed by ``solver.options``, so
            the rerun uses the settings of the original fit even if the
            installed optimizer defaults have changed.

        Raises
        ------
        ValueError
            If the record has no solver settings.

        Notes
        -----
        The two mappings share no key (``SolverSettings`` rejects it). To
        rerun with only the options as the caller wrote them, under the
        installed defaults, replace ``optim_options`` by
        ``record.solver.options``.

        The rerun passes the recorded defaults explicitly, so a record
        captured with ``from_estimation`` from the rerun estimator lists
        them as given ``options``, and its ``default_options`` holds only
        options neither record states (``{}`` for LM). The effective
        settings, ``options`` and ``default_options`` together, are the
        same as in this record.
        """
        if self._solver is None:
            raise ValueError(f"Record {self._case!r} has no solver settings; "
                             "it was not fitted")
        bounds = [(item.lower, item.upper) for item in self._parameters
                  if item.optimized]  # [parameter units]
        if all(pair == (None, None) for pair in bounds):
            bounds = None
        optim_options = self._solver.default_options or {}
        optim_options.update(self._solver.options)
        return {'method': self._solver.method,
                'optim_options': optim_options, 'bounds': bounds}

    def check_rerun(self, estimator: ParameterEstimation, *, rtol: float,
                    atol: float) -> np.ndarray:
        """Check that a rerun fit reproduces the recorded fitted values.

        Parameters
        ----------
        estimator : ParameterEstimation
            Estimator built from ``estimation_inputs`` and fitted with
            ``optimizer_inputs``.
        rtol : float
            Relative tolerance [-], finite and non-negative; the caller
            states why it is adequate for the model and solver.
        atol : float
            Absolute tolerance in parameter units, finite and
            non-negative.

        Returns
        -------
        numpy.ndarray
            Absolute differences between rerun and recorded fitted values,
            shape ``(k,)`` in optimized-parameter order and units.

        Raises
        ------
        TypeError
            If ``rtol`` or ``atol`` is not a real number.
        ValueError
            If ``rtol`` or ``atol`` is negative or not finite, the record
            has no fitted values, or the estimator has not been fitted or
            differs in experiment order, parameter names or optimize flags.
        RerunMismatchError
            If a rerun value is not finite or
            ``|rerun - recorded| > atol + rtol * |recorded|`` for any
            parameter.
        """
        tolerances = {}
        for label, value in (('rtol', rtol), ('atol', atol)):
            value = _finite_float(value, label)  # [-] or [parameter units]
            if value < 0:
                raise ValueError(f"{label} must be non-negative; got "
                                 f"{value!r}")
            tolerances[label] = value
        rtol, atol = tolerances['rtol'], tolerances['atol']
        recorded = self.fitted_values  # [parameter units]
        if recorded is None:
            raise ValueError(f"Record {self._case!r} has no fitted values")
        if not hasattr(estimator, 'params_convg'):
            raise ValueError("The estimator has not been fitted; call "
                             "optimize_fn(**record.optimizer_inputs())")
        names = [item.name for item in self._parameters]
        flags = [item.optimized for item in self._parameters]
        if (list(estimator.experim_names) != list(self._experiments)
                or list(estimator.name_params_total) != names
                or [bool(flag) for flag in estimator.map_variable]
                != flags):
            raise ValueError(
                "The estimator was not built from this record: experiment "
                "order, parameter names or optimize flags differ")
        rerun = np.asarray(estimator.params_convg,
                           dtype=np.float64)  # [parameter units]
        difference = np.abs(rerun - recorded)  # [parameter units]
        outside = ~np.isfinite(rerun) | (
            difference > atol + rtol * np.abs(recorded))
        if outside.any():
            optimized = [name for name, flag in zip(names, flags) if flag]
            raise RerunMismatchError(
                "Rerun fitted parameters differ from the record "
                f"{self._case!r} beyond rtol={rtol!r}, atol={atol!r}: " +
                ', '.join(f"{name}: rerun {float(new)!r}, recorded "
                          f"{float(old)!r}"
                          for name, new, old, bad in zip(
                              optimized, rerun, recorded, outside) if bad))
        return difference

    def rerun(self, func, *, rtol: float, atol: float,
              **estimator_options) -> ParameterEstimation:
        """Rebuild the estimation, refit it and check the fitted values.

        Parameters
        ----------
        func : callable
            Model callback of the original fit, identified by ``model``.
        rtol : float
            Relative tolerance [-] of ``check_rerun``.
        atol : float
            Absolute tolerance of ``check_rerun``, in parameter units.
        **estimator_options
            Further ``ParameterEstimation`` arguments that a record cannot
            hold because they are callables: ``jac_fun`` and a callable
            ``dx_finitediff``, required when ``solver.derivatives`` says
            the original fit used them; pass the original functions. They
            take precedence over ``estimation_inputs``.

        Returns
        -------
        ParameterEstimation
            The fitted estimator.

        Raises
        ------
        TypeError, ValueError
            See ``optimizer_inputs`` and ``check_rerun``; also ValueError
            if the record says ``jac_fun`` or a callable ``dx_finitediff``
            was used and ``estimator_options`` does not supply it.
            Tolerances and derivative inputs are validated before any model
            evaluation.
        RerunMismatchError
            If the fitted values are not reproduced within tolerance.
        """
        for label, value in (('rtol', rtol), ('atol', atol)):
            if _finite_float(value, label) < 0:
                raise ValueError(f"{label} must be non-negative; got "
                                 f"{value!r}")
        derivatives = (None if self._solver is None
                       else self._solver.derivatives)
        if derivatives is not None:
            if (derivatives['jacobian'] == 'jac_fun'
                    and estimator_options.get('jac_fun') is None):
                raise ValueError(
                    f"Record {self._case!r} was fitted with a jac_fun, "
                    "which a record cannot hold; pass the original function "
                    "as rerun(..., jac_fun=...)")
            step = derivatives['dx_finitediff']  # descriptor or step
            if (isinstance(step, str) and step == 'callable'
                    and estimator_options.get('dx_finitediff') is None):
                raise ValueError(
                    f"Record {self._case!r} was fitted with a callable "
                    "dx_finitediff, which a record cannot hold; pass it as "
                    "rerun(..., dx_finitediff=...)")
        inputs = self.estimation_inputs()
        inputs.update(estimator_options)
        estimator = ParameterEstimation(func, **inputs)
        estimator.optimize_fn(verbose=False, **self.optimizer_inputs())
        self.check_rerun(estimator, rtol=rtol, atol=atol)
        return estimator

    # ------------------------------------------------------------- capture
    @classmethod
    def from_estimation(cls, estimator: ParameterEstimation,
                        experiments: Mapping, *, case: str,
                        parameter_units, model: ModelRevision,
                        sources: Sequence, transformations: Sequence = (),
                        bounds=_UNSET,
                        model_solver: Optional[Mapping] = None,
                        weight_matrix=None,
                        covariance_include_mse: bool = True,
                        fields: Sequence = (),
                        description: Optional[str] = None
                        ) -> 'CalibrationRecord':
        """Capture a fitted ``ParameterEstimation`` built from experiments.

        Parameters
        ----------
        estimator : ParameterEstimation
            Estimator built with ``x_data=experiments``, directly or
            through ``SimulationExec.SetParamEstimation``, and fitted with
            ``optimize_fn``. It is left unchanged.
        experiments : Mapping[str, Experiment]
            The ``Experiment`` objects given as ``x_data``, with the same
            names in the same order. They are only read.
        case : str
            Calibration case identifier.
        parameter_units : Mapping[str, str] or sequence of str
            Units of every parameter, by name or in parameter order.
        model : ModelRevision
            Calibrated model, recorded as given: its ``pharmapy_version`` is
            the one it holds (detected when it was built, or stored in a
            loaded record), never detected again here. Build a new
            ``ModelRevision`` to record the running PharmaPy version.
        sources : sequence of DataSource
            Data sources.
        transformations : sequence of Transformation, optional
            Data transformations in application order.
        bounds : sequence of (float or None, float or None), optional
            One ``(lower, upper)`` pair per optimized parameter, in
            parameter units. Required for IPOPT fits: pass the ``bounds``
            given to ``optimize_fn`` (``(None, None)`` pairs for unbounded
            parameters), because ``optimize_fn`` does not store them and
            they cannot be verified against the fit. For LM fits they are
            optional and recorded as declared parameter ranges; LM ignores
            bounds.
        model_solver : Mapping, optional
            Settings of the model's own solver, for documentation.
        weight_matrix : pandas.DataFrame, optional
            The ``weight_matrix`` given to the estimator. Required if and
            only if the estimator uses one; it must equal the estimator's
            effective covariance.
        covariance_include_mse : bool, optional
            Form of the recorded parameter covariance,
            ``get_covariance(include_mse=covariance_include_mse)``. The
            default True is the form ``optimize_fn`` returns.
        fields : sequence of FieldRecord, optional
            Further stored fields (states, algebraic variables, quality
            attributes); they precede the measurement predictions.
        description : str, optional
            Free-text description.

        Returns
        -------
        CalibrationRecord
            Record holding the experiments with their effective callback
            inputs (see Notes); the estimator's parameter
            seeds, optimize flags, names and fitted values; the optimizer
            method, options (``estimator.optim_options`` without the
            entries ``optimize_fn`` injects itself: ``full_output`` and
            ``verbose`` for LM, ``print_level`` for IPOPT; issue #476) and
            outcome. For LM, ``default_options`` holds the
            ``levenberg_marquardt`` keyword defaults of every option the
            caller did not set (issue #483; see ``SolverSettings``). For
            IPOPT, cyipopt rewrites the copy of the options that
            ``optimize_fn`` passes to it and stores (#476), so its bytes
            keys and values are decoded to str and the entries it writes
            (``tol``, ``mu_strategy``, ``hessian_approximation``) are kept;
            Ipopt's native defaults are not recorded and ``default_options``
            is None. The solver settings also record how
            the sensitivities were obtained (``derivatives``: the Jacobian
            source and ``dx_finitediff`` as ``'default'``, ``'callable'``
            or the numeric step). Also the covariance in the
            requested form, and ``fields`` followed by one
            ``'measurement_prediction'`` record per experiment and
            measurement column. A prediction is the model output of that
            column (``estimator.y_runs``) on the experiment's full model
            grid ``x_model``, at the accepted parameters, in the
            measurement's units and basis: per measurement name the first
            units and basis declared in any experiment.

        Raises
        ------
        TypeError
            If ``estimator`` is not a ``ParameterEstimation``,
            ``experiments`` is not a mapping or holds a value that is not an
            ``Experiment``, ``parameter_units`` or
            ``bounds`` is not a list or tuple, a SimulationExec wrapper
            keyword value or a numeric ``dx_finitediff`` cannot be
            recorded, or a provenance entry has the wrong type (see the
            record classes).
        ValueError
            If the estimator has not been fitted, its last ``optimize_fn``
            ran with ``simulate=True``, its stored model outputs are not
            those of the accepted parameters, it was not compiled from
            ``experiments`` (see Notes), its parameter names do not match
            its parameters, units are not given for exactly its parameters,
            ``bounds`` is missing for IPOPT, has the wrong length or holds
            a pair that is not ``(lower, upper)`` with ``lower <= upper``,
            the weight matrix is missing, unexpected or different from the
            estimator's, an IPOPT option is not UTF-8 text, or a recorded
            value is not finite.
        numpy.linalg.LinAlgError
            If the covariance cannot be computed (singular ``J @ J.T``).

        Notes
        -----
        The experiments are compiled with the estimator's compile path and
        must reproduce exactly its measurement columns, resolved fields,
        model grids, observations (NaN positions included) and standard
        deviations. Callback inputs are compared exactly in type, value
        and order: positional ``args`` must be equal, and every keyword of
        an experiment must be passed with an equal value, in the
        experiment's order. The estimator may pass additional keywords only
        if they are ``SimulationExec`` wrapper keywords (``modify_phase``,
        ``modify_controls``, ``run_args``), which ``SetParamEstimation``
        adds to its own copy of each experiment. The record stores the
        effective inputs: each experiment's keywords followed by those
        wrapper keywords with the values the fit used, so the record
        reruns both through ``rerun(unit.paramest_wrapper, ...)`` and
        through ``SetParamEstimation(record.experiments, ...)`` without
        modifier arguments.

        The derivative descriptor recognizes the default step closure that
        ``ParameterEstimation`` installs when ``dx_finitediff`` is None by
        its qualified name, ``ParameterEstimation.__init__.<locals>.
        dparam_fun``; any other callable is recorded as ``'callable'``.

        The covariance is obtained by calling ``get_covariance``, after
        which ``covar_params`` and ``correl_params`` are restored, so the
        estimator is left as it was. The recorded ``'objective'`` outcome
        is ``1/2 * fun @ fun`` of the weighted residuals
        ``info_opt['fun']`` ([-] with declared uncertainties), so the model
        is not evaluated again.

        An estimator fitted by ``rerun`` (or with ``optimizer_inputs``)
        received the recorded defaults as explicit options, so its record
        lists them as given ``options`` and its ``default_options`` is
        ``{}`` for LM; the effective settings are identical to those of the
        record it was rerun from.
        """
        if not isinstance(estimator, ParameterEstimation):
            raise TypeError("estimator must be a ParameterEstimation; got "
                            f"{type(estimator).__name__}")
        if not hasattr(estimator, 'params_convg'):
            raise ValueError("The estimator has not been fitted; call "
                             "optimize_fn before capturing it")
        if not isinstance(experiments, Mapping):
            raise TypeError("experiments must be the mapping of Experiment "
                            "objects passed as x_data; got "
                            f"{type(experiments).__name__}")
        for name, value in experiments.items():
            if not isinstance(value, Experiment):
                raise TypeError(f"experiments[{name!r}] must be an "
                                f"Experiment; got {type(value).__name__}")
        if not estimator.optimize_flag:
            raise ValueError(
                "The estimator's last optimize_fn ran with simulate=True, "
                "which evaluates without fitting; fit it with "
                "simulate=False before capturing it")
        if list(estimator.experim_names) != list(experiments):
            raise ValueError(
                f"The estimator experiments {estimator.experim_names!r} "
                f"differ from {list(experiments)!r}; pass the mapping used "
                "as x_data, in the same order")
        effective = _check_estimator_data(estimator, experiments)
        if not np.array_equal(estimator.params_residuals,
                              estimator.params_convg):
            raise ValueError(
                "The estimator's stored model outputs (y_runs) were not "
                "evaluated at its accepted parameters params_convg")
        columns = list(estimator._measurement_names)

        if weight_matrix is not None:
            if estimator._residual_std is not None:
                raise ValueError(
                    "weight_matrix must be None: the estimator's "
                    "measurements declare uncertainties")
            symmetric = _weight_matrix_array(weight_matrix,
                                             columns)  # [u_i * u_j]
            if not np.array_equal(symmetric,
                                  estimator._measurement_covariance):
                raise ValueError("weight_matrix differs from the estimator's "
                                 "measurement-error covariance")
        elif not np.array_equal(estimator._measurement_covariance,
                                np.eye(len(columns))):
            raise ValueError("The estimator uses a weight_matrix; pass it to "
                             "record the weighting of the fit")

        names = list(estimator.name_params_total)
        seeds = np.asarray(estimator.param_seed,
                           dtype=np.float64)  # [parameter units]
        flags = [bool(flag) for flag in estimator.map_variable]
        if len(names) != len(seeds):
            raise ValueError(
                f"The estimator has {len(seeds)} parameters but "
                f"{len(names)} names {names!r}; pass name_params with one "
                "name per parameter")
        if isinstance(parameter_units, Mapping):
            if set(parameter_units) != set(names):
                raise ValueError(
                    f"parameter_units keys {list(parameter_units)!r} must be "
                    f"exactly the parameter names {names!r}")
            units = [parameter_units[name] for name in names]
        else:
            units = list(_sequence(parameter_units, 'parameter_units'))
            if len(units) != len(names):
                raise ValueError(f"parameter_units needs one entry per "
                                 f"parameter {names!r}")
        method = estimator.opt_method
        num_optimized = sum(flags)  # [-]
        if bounds is _UNSET:
            if method == 'IPOPT':
                raise ValueError(
                    "bounds is required for IPOPT fits: pass the bounds "
                    "given to optimize_fn ((None, None) pairs for unbounded "
                    "parameters); optimize_fn does not store them")
            bounds = [(None, None)] * num_optimized
        bounds = list(_sequence(bounds, 'bounds'))  # [parameter units]
        if len(bounds) != num_optimized:
            raise ValueError(f"bounds needs one (lower, upper) pair per "
                             f"optimized parameter ({num_optimized})")
        fitted = iter(np.asarray(estimator.params_convg,
                                 dtype=np.float64))  # [parameter units]
        bound_pairs = iter(bounds)  # [parameter units]
        parameters = []
        for name, unit, seed, flag in zip(names, units, seeds, flags):
            pair = (_sequence(next(bound_pairs), f'bounds of {name!r}')
                    if flag else (None, None))  # [parameter units]
            if len(pair) != 2:
                raise ValueError(f"bounds of {name!r} must be a (lower, "
                                 f"upper) pair; got {pair!r}")
            lower, upper = pair  # [parameter units]
            parameters.append(ParameterRecord(
                name, unit, seed, lower=lower, upper=upper, optimized=flag,
                fitted=next(fitted) if flag else None))

        info = estimator.info_opt
        outcome = {key: (str(info[key]) if key == 'stop_criterion'
                         else int(info[key]))
                   for key in ('stop_criterion', 'num_iter', 'num_fun_eval')
                   if key in info}
        # Weighted residuals: [-] with declared uncertainties, otherwise the
        # measurement units divided by the root of the weight units.
        residuals = np.asarray(info['fun'], dtype=np.float64)
        # [residual units**2]; 1/2 r @ r, the objective of
        # ParameterEstimation.get_objective.
        outcome['objective'] = 0.5 * float(residuals @ residuals)
        options = _effective_options(getattr(estimator, 'optim_options', {}),
                                     method)
        default_options = _default_options(method, options)
        if estimator.sens_second is not None:
            jacobian = 'model_sensitivities'  # precedence of get_gradient
        elif estimator.jac_fun is not None:
            jacobian = 'jac_fun'
        else:
            jacobian = 'finite_difference'
        step = estimator.dx_fd  # [parameter units] if numeric
        if (callable(step) and getattr(step, '__qualname__', None)
                == _DEFAULT_STEP_QUALNAME
                and getattr(step, '__module__', None)
                == ParameterEstimation.__module__):
            step = 'default'
        elif callable(step):
            step = 'callable'
        solver = SolverSettings(method, options=options,
                                default_options=default_options,
                                model_solver=model_solver, outcome=outcome,
                                derivatives={'jacobian': jacobian,
                                             'dx_finitediff': step})

        stored = {name: getattr(estimator, name)
                  for name in ('covar_params', 'correl_params')
                  if hasattr(estimator, name)}
        try:
            covariance = np.array(estimator.get_covariance(
                include_mse=covariance_include_mse))  # [u_i * u_j]
        finally:
            for name in ('covar_params', 'correl_params'):
                if name in stored:
                    setattr(estimator, name, stored[name])
                elif hasattr(estimator, name):
                    delattr(estimator, name)

        units_by_name, basis_by_name, x_units = _declared_metadata(
            experiments)
        predictions = []
        for experiment_name, x_model, y_run in zip(
                estimator.experim_names, estimator.x_model,
                estimator.y_runs):
            for column, name in enumerate(columns):
                unit, basis = units_by_name[name], basis_by_name[name]
                if unit is None or x_units is None:
                    raise ValueError(
                        f"Measurement {name!r} of experiment "
                        f"{experiment_name!r} must declare units and "
                        "x_units to record its prediction")
                predictions.append(FieldRecord(
                    FieldIdentity(name, 'measurement_prediction', unit,
                                  basis=basis),
                    x_model, np.asarray(y_run)[:, column],
                    x_units=x_units, experiment=experiment_name))

        return cls(case, effective, parameters, sources, model,
                   description=description,
                   output_names=estimator.output_names,
                   transformations=transformations, solver=solver,
                   fields=tuple(_sequence(fields, 'fields'))
                   + tuple(predictions),
                   weight_matrix=weight_matrix, covariance=covariance,
                   covariance_include_mse=covariance_include_mse)

    def __repr__(self) -> str:
        """Return a short representation.

        Returns
        -------
        str
            Case, experiment names and parameter names.
        """
        return (f"CalibrationRecord(case={self._case!r}, experiments="
                f"{list(self._experiments)!r}, parameters="
                f"{[item.name for item in self._parameters]!r})")


