def template_text(name: str = 'calibration_record') -> str:
    """Return the JSON text of a record template shipped with PharmaPy.

    Write the text to a file, replace its template entries with the
    case's data and provenance, and read it with ``CalibrationRecord.load``.

    Parameters
    ----------
    name : str, optional
        Template name, one of ``TEMPLATE_NAMES``. The default
        ``'calibration_record'`` is an unfitted record (``solver``,
        ``covariance`` and ``weight_matrix`` are null) with one experiment
        of two measurements, one missing observation (``null``),
        per-sample uncertainties, callback ``args`` and ``kwargs``, a data
        source, a transformation, a bounded parameter, a model revision and
        a stored state. Its text entries starting with
        ``'TEMPLATE'`` are placeholders; its numbers are the synthetic
        decay example of the user guide, not data.

    Returns
    -------
    str
        UTF-8 decoded JSON text, exactly as ``CalibrationRecord.to_json``
        writes the template record.

    Raises
    ------
    ValueError
        If ``name`` is not one of ``TEMPLATE_NAMES``.

    Notes
    -----
    The templates are package data of PharmaPy (``PharmaPy/data/records``)
    read through ``importlib.resources``, so they are available in
    installed distributions, not only in a source checkout.
    """
    name = _choice(name, TEMPLATE_NAMES, 'Template name')
    resource = files('PharmaPy').joinpath(
        f'{_TEMPLATE_DIRECTORY}/{name}_template.json')
    return resource.read_text(encoding='utf-8')


def load_template(name: str = 'calibration_record') -> CalibrationRecord:
    """Read a record template shipped with PharmaPy.

    Parameters
    ----------
    name : str, optional
        Template name, one of ``TEMPLATE_NAMES``; see ``template_text``.

    Returns
    -------
    CalibrationRecord
        New record holding the template entries.

    Raises
    ------
    ValueError
        If ``name`` is not one of ``TEMPLATE_NAMES``.
    """
    return CalibrationRecord.from_json(template_text(name))
