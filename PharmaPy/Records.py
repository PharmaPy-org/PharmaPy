def _text(value, label: str, *, optional: bool = False) -> Optional[str]:
    """Validate a non-empty str.

    Parameters
    ----------
    value : str or None
        Value to validate.
    label : str
        Input name used in error messages.
    optional : bool, optional
        If True, None is accepted and returned. The default is False.

    Returns
    -------
    str or None
        ``value`` unchanged.

    Raises
    ------
    TypeError
        If ``value`` is not a str (or None when ``optional``).
    ValueError
        If ``value`` is an empty str.
    """
    if value is None and optional:
        return None
    if not isinstance(value, str):
        expected = 'a str or None' if optional else 'a str'
        raise TypeError(f"{label} must be {expected}; got "
                        f"{type(value).__name__}")
    if not value:
        raise ValueError(f"{label} must be a non-empty str")
    return value


def _choice(value, choices: tuple, label: str) -> str:
    """Validate a finite-choice option.

    Parameters
    ----------
    value : str
        Selected option.
    choices : tuple of str
        Admissible options.
    label : str
        Input name used in error messages.

    Returns
    -------
    str
        ``value`` unchanged.

    Raises
    ------
    ValueError
        If ``value`` is not one of ``choices``.
    """
    if not isinstance(value, str) or value not in choices:
        raise ValueError(f"{label} must be one of {choices!r}; got "
                         f"{value!r}")
    return value


def _finite_float(value, label: str, *,
                  optional: bool = False) -> Optional[float]:
    """Validate a finite real number.

    Parameters
    ----------
    value : numbers.Real or None
        Value to validate; units are preserved.
    label : str
        Input name used in error messages.
    optional : bool, optional
        If True, None is accepted and returned. The default is False.

    Returns
    -------
    float or None
        ``value`` as a built-in float, in its own units.

    Raises
    ------
    TypeError
        If ``value`` is a bool or not a real number.
    ValueError
        If ``value`` is NaN, infinite or too large for a float.
    """
    if value is None and optional:
        return None
    if isinstance(value, (bool, np.bool_)) or not isinstance(
            value, numbers.Real):
        raise TypeError(f"{label} must be a real number; got "
                        f"{type(value).__name__}")
    try:
        number = float(value)  # [units of value]
    except OverflowError as error:
        raise ValueError(f"{label} = {value!r} is too large for a float"
                         ) from error
    if not np.isfinite(number):
        raise ValueError(f"{label} must be finite; got {number!r}")
    return number


def _unique_names(names: list, label: str) -> None:
    """Reject repeated names.

    Parameters
    ----------
    names : list of str
        Names in declared order.
    label : str
        Collection name used in error messages.

    Raises
    ------
    ValueError
        If a name appears more than once; repeated names are listed in
        first-occurrence order, so names of mixed types (e.g. None and
        str) are reported without sorting.
    """
    repeated = list(dict.fromkeys(name for name in names
                                  if names.count(name) > 1))
    if repeated:
        raise ValueError(f"{label} names must be unique; repeated "
                         f"{repeated!r}")


def _sequence(value, label: str) -> tuple:
    """Return a list or tuple argument as a tuple.

    Parameters
    ----------
    value : list or tuple
        Ordered collection.
    label : str
        Input name used in error messages.

    Returns
    -------
    tuple
        Entries in the given order.

    Raises
    ------
    TypeError
        If ``value`` is not a list or tuple.
    """
    if not isinstance(value, (list, tuple)):
        raise TypeError(f"{label} must be a list or tuple; got "
                        f"{type(value).__name__}")
    return tuple(value)


def _check_keys(data, required: tuple, optional: tuple, label: str) -> None:
    """Validate the keys of a deserialized JSON object.

    Parameters
    ----------
    data : dict
        Deserialized JSON object.
    required : tuple of str
        Keys that must be present.
    optional : tuple of str
        Keys that may be present.
    label : str
        Object name used in error messages.

    Raises
    ------
    TypeError
        If ``data`` is not a dict.
    ValueError
        If a required key is missing or an unknown key is present.
    """
    if not isinstance(data, dict):
        raise TypeError(f"{label} must be a JSON object; got "
                        f"{type(data).__name__}")
    missing = [key for key in required if key not in data]
    unknown = [key for key in data if key not in required + optional]
    if missing or unknown:
        raise ValueError(
            f"{label} has missing keys {missing!r} and unknown keys "
            f"{unknown!r}; allowed keys are {list(required + optional)!r}")


