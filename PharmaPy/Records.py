def _encode_experiment(name: str, experiment: Experiment) -> dict:
    """Serialize one experiment and its measurements.

    Parameters
    ----------
    name : str
        Experiment name.
    experiment : Experiment
        Experiment to serialize. Every measurement must declare ``units``
        and ``x_units``.

    Returns
    -------
    dict
        JSON object with keys ``name``, ``args``, ``kwargs`` and
        ``measurements`` (a list in declared order).

    Raises
    ------
    TypeError
        If ``experiment`` is not an ``Experiment`` or a callback argument
        cannot be recorded.
    ValueError
        If a measurement leaves ``units`` or ``x_units`` undeclared,
        declares an empty basis, an uncertainty entry at a missing sample is
        infinite, or a callback argument is not finite.
    """
    if not isinstance(experiment, Experiment):
        raise TypeError(f"experiments[{name!r}] must be an Experiment; got "
                        f"{type(experiment).__name__}")
    path = f'experiments[{name!r}]'
    measurements = []
    for measurement_name, measurement in experiment.measurements.items():
        label = f'{path}.measurements[{measurement_name!r}]'
        for attribute in ('units', 'x_units'):
            if not getattr(measurement, attribute):
                raise ValueError(
                    f"{label} must declare {attribute}: a calibration record "
                    "documents the units of every observation")
        if measurement.basis == '':
            raise ValueError(f"{label} declares an empty basis; pass None "
                             "for an undeclared basis")
        uncertainty = measurement.uncertainty  # [units]
        measurements.append({
            'name': measurement_name, 'field': measurement.field,
            'units': measurement.units, 'basis': measurement.basis,
            'x_units': measurement.x_units,
            'x': _float_list(measurement.x, f'{label}.x'),
            'values': _float_list(measurement.values, f'{label}.values'),
            'uncertainty': (None if uncertainty is None else
                            _float_list(uncertainty,
                                        f'{label}.uncertainty'))})
    return {'name': name,
            'args': [_encode_value(value, f'{path}.args[{index}]')
                     for index, value in enumerate(experiment.args)],
            'kwargs': _encode_mapping(experiment.kwargs, f'{path}.kwargs'),
            'measurements': measurements}


def _decode_experiment(data: dict) -> Experiment:
    """Reconstruct an experiment written by ``_encode_experiment``.

    Parameters
    ----------
    data : dict
        JSON object of one experiment, without its ``name`` key.

    Returns
    -------
    Experiment
        New experiment with new measurements and callback arguments.

    Raises
    ------
    TypeError, ValueError
        If ``data`` is malformed or the measurements are invalid.
    """
    _check_keys(data, ('args', 'kwargs', 'measurements'), (), 'Experiment')
    if type(data['measurements']) is not list:
        raise TypeError("Experiment measurements must be a JSON array")
    measurements = {}
    for item in data['measurements']:
        _check_keys(item, ('name', 'field', 'units', 'x_units', 'x',
                           'values'), ('basis', 'uncertainty'), 'Measurement')
        name = _text(item['name'], 'Measurement name')
        if name in measurements:
            raise ValueError(f"Measurement name {name!r} is repeated")
        label = f'Measurement {name!r}'
        uncertainty = item.get('uncertainty')
        measurements[name] = Measurement(
            item['field'], _float_array(item['x'], f'{label} x'),
            _float_array(item['values'], f'{label} values'),
            uncertainty=(None if uncertainty is None else
                         _float_array(uncertainty, f'{label} uncertainty')),
            units=item['units'], basis=item.get('basis'),
            x_units=item['x_units'])
    if type(data['args']) is not list:
        raise TypeError("Experiment args must be a JSON array")
    args = tuple(_decode_value(value, f'args[{index}]')
                 for index, value in enumerate(data['args']))
    return Experiment(measurements, args=args,
                      kwargs=_decode_mapping(data['kwargs'], 'kwargs'))


