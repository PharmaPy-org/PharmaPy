def _numeric_dtype(dtype, path: str) -> None:
    """Reject dtypes that a JSON record cannot hold exactly.

    Parameters
    ----------
    dtype : numpy.dtype
        Dtype of a NumPy scalar or array.
    path : str
        Location of the value used in error messages.

    Raises
    ------
    TypeError
        If ``dtype`` is structured, carries metadata, is not boolean,
        integer or floating, or is a floating type wider than IEEE 754
        binary64 (e.g. ``numpy.longdouble``).
    """
    if dtype.fields is not None or dtype.subdtype is not None:
        raise TypeError(
            f"{path} has structured NumPy dtype {dtype}; only plain "
            "boolean, integer and floating values can be recorded")
    if dtype.metadata is not None:
        raise TypeError(
            f"{path} has a NumPy dtype carrying metadata "
            f"{dict(dtype.metadata)!r}, which a record cannot restore; "
            "pass a plain dtype")
    if dtype.kind not in _NUMERIC_KINDS:
        raise TypeError(
            f"{path} has unsupported NumPy dtype {dtype}; only boolean, "
            "integer and floating (at most 64-bit) values can be recorded")
    if dtype.kind == 'f' and dtype.itemsize > _MAX_FLOAT_ITEMSIZE:
        raise TypeError(
            f"{path} has NumPy dtype {dtype}, wider than 64 bits; JSON "
            "numbers are binary64, so it cannot be recorded exactly. Convert "
            "it to float64 first")


def _encode_value(value, path: str):
    """Encode a callback argument or option value as JSON data.

    Parameters
    ----------
    value : object
        ``None``, ``bool``, ``int``, finite ``float``, ``str``, list,
        dict with str keys, tuple, NumPy scalar or ``numpy.ndarray`` (not a
        subclass) of boolean, integer or at most 64-bit floating dtype;
        containers are encoded recursively.
    path : str
        Location of ``value`` used in error messages, e.g.
        ``"experiments['hot'].args[0]"``.

    Returns
    -------
    object
        JSON-compatible data; tuples and NumPy values become objects tagged
        by ``'__type__'``. NumPy values keep their dtype including byte
        order (``dtype.str``).

    Raises
    ------
    TypeError
        If ``value`` (or a nested entry) has an unsupported type, a dict key
        is not a str, an array is an ndarray subclass (e.g.
        ``numpy.matrix`` or a masked array), or a NumPy dtype is
        non-numeric, complex or wider than 64 bits.
    ValueError
        If a float is NaN or infinite, or a dict uses the reserved key
        ``'__type__'``.
    """
    if value is None or type(value) in (bool, int, str):
        return value
    if type(value) is float:
        if not np.isfinite(value):
            raise ValueError(
                f"{path} = {value!r} cannot be recorded: JSON records hold "
                "finite floats only")
        return value
    if isinstance(value, np.generic):
        _numeric_dtype(value.dtype, path)
        item = value.item()
        if value.dtype.kind == 'f' and not np.isfinite(item):
            raise ValueError(
                f"{path} = {item!r} cannot be recorded: JSON records hold "
                "finite floats only")
        return {_TYPE_TAG: 'numpy_scalar', 'dtype': value.dtype.str,
                'value': item}
    if isinstance(value, np.ndarray):
        if type(value) is not np.ndarray:
            raise TypeError(
                f"{path} is a {type(value).__name__}, an ndarray subclass "
                "whose behaviour a record cannot restore; pass a plain "
                "numpy.ndarray")
        _numeric_dtype(value.dtype, path)
        if value.dtype.kind == 'f' and not np.isfinite(value).all():
            raise ValueError(
                f"{path} holds NaN or infinite entries, which JSON records "
                "cannot hold in callback arguments or options")
        return {_TYPE_TAG: 'ndarray', 'dtype': value.dtype.str,
                'shape': list(value.shape), 'data': value.ravel().tolist()}
    if type(value) is tuple:
        return {_TYPE_TAG: 'tuple',
                'items': [_encode_value(item, f'{path}[{index}]')
                          for index, item in enumerate(value)]}
    if type(value) is list:
        return [_encode_value(item, f'{path}[{index}]')
                for index, item in enumerate(value)]
    if type(value) is dict:
        return _encode_mapping(value, path)
    raise TypeError(
        f"{path} has unsupported type {type(value).__name__}; records hold "
        "None, bool, int, float, str, list, tuple, dict with str keys, "
        "NumPy scalars and numeric NumPy arrays. Pass model objects such as "
        "phases or callables through the model callback instead")


def _encode_mapping(mapping, path: str) -> dict:
    """Encode a mapping with str keys as a JSON object.

    Parameters
    ----------
    mapping : Mapping
        Mapping of str keys to values supported by ``_encode_value``.
    path : str
        Location of ``mapping`` used in error messages.

    Returns
    -------
    dict
        Encoded values in the mapping's iteration order.

    Raises
    ------
    TypeError
        If ``mapping`` is not a mapping, a key is not a str or a value has
        an unsupported type.
    ValueError
        If a key is the reserved ``'__type__'`` or a value is not finite.
    """
    if not isinstance(mapping, Mapping):
        raise TypeError(f"{path} must be a mapping; got "
                        f"{type(mapping).__name__}")
    encoded = {}
    for key, value in mapping.items():
        if not isinstance(key, str):
            raise TypeError(f"{path} keys must be str; got "
                            f"{type(key).__name__} {key!r}")
        if key == _TYPE_TAG:
            raise ValueError(f"{path} uses the reserved key {_TYPE_TAG!r}")
        encoded[key] = _encode_value(value, f'{path}[{key!r}]')
    return encoded


def _decode_numbers(items: list, dtype: np.dtype, path: str) -> np.ndarray:
    """Convert JSON numbers to a one-dimensional array of a recorded dtype.

    Parameters
    ----------
    items : list
        Flat JSON entries.
    dtype : numpy.dtype
        Recorded dtype, boolean, integer or at most 64-bit floating.
    path : str
        Location used in error messages.

    Returns
    -------
    numpy.ndarray
        New array of ``dtype``, shape ``(len(items),)``.

    Raises
    ------
    TypeError
        If an entry has the wrong JSON type for ``dtype``: booleans for a
        boolean dtype, integers (not booleans) for an integer dtype, and
        integers or floats (not booleans) for a floating dtype.
    ValueError
        If an entry is out of range for ``dtype``, is not finite, or does
        not round-trip exactly through ``dtype``. Ranges are checked with
        ``numpy.iinfo``/``numpy.finfo`` before conversion, so the result
        does not depend on the NumPy version.
    """
    if dtype.kind == 'b':
        allowed, expected = (bool,), 'JSON booleans'
    elif dtype.kind in 'iu':
        allowed, expected = (int,), 'JSON integers'
    else:
        allowed, expected = (int, float), 'JSON numbers'
    if dtype.kind in 'iu':
        limits = np.iinfo(dtype)
        lowest, highest = int(limits.min), int(limits.max)
    elif dtype.kind == 'f':
        limits = np.finfo(dtype)
        lowest, highest = float(limits.min), float(limits.max)
    for index, item in enumerate(items):
        if type(item) not in allowed:
            raise TypeError(f"{path}[{index}] must be one of the {expected} "
                            f"of dtype {dtype}; got {type(item).__name__} "
                            f"{item!r}")
        if dtype.kind == 'b':
            continue
        if dtype.kind == 'f':
            try:
                number = float(item)  # [units of the value]
            except OverflowError:
                number = np.inf if item > 0 else -np.inf  # out of range
            if not np.isfinite(number) and type(item) is float:
                raise ValueError(f"{path}[{index}] = {item!r} is not finite")
        else:
            number = item
        # Checked here rather than by NumPy, which raises OverflowError on
        # NumPy 2 but wraps with a DeprecationWarning on NumPy 1.x.
        if not lowest <= number <= highest:
            raise ValueError(f"{path}[{index}] = {item!r} is out of range "
                             f"for dtype {dtype} [{lowest!r}, {highest!r}]")
    array = np.array(items, dtype=dtype)
    if array.tolist() != items:
        raise ValueError(f"{path} holds values that dtype {dtype} cannot "
                         "represent exactly")
    return array


def _decode_value(data, path: str):
    """Decode JSON data written by ``_encode_value``.

    Parameters
    ----------
    data : object
        JSON data.
    path : str
        Location of ``data`` used in error messages.

    Returns
    -------
    object
        New Python object equal in type and value to the encoded one.

    Raises
    ------
    TypeError
        If ``data`` holds a non-JSON type, a malformed tagged object, a
        dtype that is not a str, or entries of the wrong JSON type for
        their dtype.
    ValueError
        If a tagged object has an unknown tag or dtype, an inconsistent
        shape, an entry out of range or not exactly representable, or a
        float is not finite.
    """
    if data is None or type(data) in (bool, int, str):
        return data
    if type(data) is float:
        if not np.isfinite(data):
            raise ValueError(f"{path} = {data!r} is not a finite float")
        return data
    if type(data) is list:
        return [_decode_value(item, f'{path}[{index}]')
                for index, item in enumerate(data)]
    if type(data) is not dict:
        raise TypeError(f"{path} has non-JSON type {type(data).__name__}")
    if _TYPE_TAG not in data:
        return {key: _decode_value(value, f'{path}[{key!r}]')
                for key, value in data.items()}

    tag = data[_TYPE_TAG]
    if tag == 'tuple':
        _check_keys(data, (_TYPE_TAG, 'items'), (), path)
        if type(data['items']) is not list:
            raise TypeError(f"{path} tuple items must be a JSON array")
        return tuple(_decode_value(item, f'{path}[{index}]')
                     for index, item in enumerate(data['items']))
    if tag not in ('numpy_scalar', 'ndarray'):
        raise ValueError(f"{path} has unknown {_TYPE_TAG!r} tag {tag!r}; "
                         "known tags are 'tuple', 'numpy_scalar' and "
                         "'ndarray'")
    keys = ('value',) if tag == 'numpy_scalar' else ('shape', 'data')
    _check_keys(data, (_TYPE_TAG, 'dtype') + keys, (), path)
    if type(data['dtype']) is not str:
        raise TypeError(f"{path} dtype must be a str such as '<f8'; got "
                        f"{type(data['dtype']).__name__}")
    try:
        dtype = np.dtype(data['dtype'])
    except TypeError as error:
        raise ValueError(f"{path} has unknown dtype "
                         f"{data['dtype']!r}") from error
    try:
        _numeric_dtype(dtype, path)
    except TypeError as error:
        raise ValueError(str(error)) from error
    if tag == 'numpy_scalar':
        return _decode_numbers([data['value']], dtype, f'{path}.value')[0]
    shape = data['shape']
    if type(shape) is not list or not all(
            type(size) is int and size >= 0 for size in shape):
        raise ValueError(f"{path} shape must be a list of non-negative ints; "
                         f"got {shape!r}")
    if type(data['data']) is not list:
        raise TypeError(f"{path} data must be a flat JSON array")
    array = _decode_numbers(data['data'], dtype, f'{path}.data')
    if array.size != math.prod(shape):  # exact Python-int product
        raise ValueError(f"{path} holds {array.size} entries, which do not "
                         f"fill shape {tuple(shape)}")
    return array.reshape(shape)


def _decode_mapping(data, path: str) -> dict:
    """Decode a JSON object written by ``_encode_mapping``.

    Parameters
    ----------
    data : dict
        JSON object of encoded values.
    path : str
        Location of ``data`` used in error messages.

    Returns
    -------
    dict
        New dict with decoded values in stored order.

    Raises
    ------
    TypeError
        If ``data`` is not a JSON object or holds malformed values.
    ValueError
        If ``data`` is a tagged object or a value is malformed.
    """
    if type(data) is not dict:
        raise TypeError(f"{path} must be a JSON object; got "
                        f"{type(data).__name__}")
    if _TYPE_TAG in data:
        raise ValueError(f"{path} uses the reserved key {_TYPE_TAG!r}")
    return {key: _decode_value(value, f'{path}[{key!r}]')
            for key, value in data.items()}


def _float_list(array: np.ndarray, label: str) -> list:
    """Encode a float array as nested JSON lists with null for NaN.

    Parameters
    ----------
    array : numpy.ndarray
        Float values of any shape; NaN marks a missing value. Units are
        preserved.
    label : str
        Array name used in error messages.

    Returns
    -------
    list
        Nested lists matching ``array.shape``; NaN entries are None.

    Raises
    ------
    ValueError
        If ``array`` holds an infinite entry, which standard JSON cannot
        represent.
    """
    infinite = np.argwhere(np.isinf(array))
    if infinite.size:
        index = tuple(int(i) for i in infinite[0])
        raise ValueError(
            f"{label}{list(index)} = {float(array[index])!r} cannot be "
            "recorded: JSON records hold finite values or NaN (missing)")
    return _nested_floats(array)


def _nested_floats(array: np.ndarray):
    """Convert a finite-or-NaN float array to nested lists.

    Parameters
    ----------
    array : numpy.ndarray
        Float values without infinities; units are preserved.

    Returns
    -------
    float, None or list
        A float or None (NaN) for a zero-dimensional array, otherwise
        nested lists matching ``array.shape``.
    """
    if array.ndim == 0:
        return None if np.isnan(array) else float(array)
    return [_nested_floats(item) for item in array]


def _float_array(data, label: str) -> np.ndarray:
    """Decode nested JSON lists written by ``_float_list``.

    Parameters
    ----------
    data : list
        Nested lists of numbers, with None for missing values.
    label : str
        Array name used in error messages.

    Returns
    -------
    numpy.ndarray
        New float64 array; None entries become NaN. Units are preserved.

    Raises
    ------
    TypeError
        If ``data`` holds entries other than numbers and None, or is
        ragged.
    ValueError
        If an integer entry is too large for a float.
    """
    def convert(item):
        """Map one JSON entry to a float.

        Parameters
        ----------
        item : object
            JSON entry or nested list.

        Returns
        -------
        float or list
            NaN for None, the float value for a number, or the converted
            nested list.

        Raises
        ------
        TypeError
            If ``item`` is a bool, str or object.
        ValueError
            If ``item`` is an integer too large for a float.
        """
        if type(item) is list:
            return [convert(entry) for entry in item]
        if item is None:
            return np.nan
        if type(item) not in (int, float):
            raise TypeError(f"{label} entries must be numbers or null; got "
                            f"{type(item).__name__} {item!r}")
        try:
            return float(item)
        except OverflowError as error:
            raise ValueError(f"{label} entry {item!r} is too large for a "
                             "float") from error

    if type(data) is not list:
        raise TypeError(f"{label} must be a JSON array; got "
                        f"{type(data).__name__}")
    converted = convert(data)  # [units of the values]
    try:
        return np.array(converted, dtype=np.float64)
    except ValueError as error:
        raise TypeError(f"{label} must be a rectangular array; "
                        f"{error}") from error


